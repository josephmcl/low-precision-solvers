/*  Does the cascade in k_saturation actually reproduce k_slice_rows?

    Everything item 6 reports rests on that replication, and a
    replication is worth exactly as much as the check that it matches.
    The per-level SCALE is the signature: it is max|hi| / 127 over the
    row, and it is determined entirely by the residual cascade, so if
    every scale agrees bit for bit at every level then the residuals
    agree at every level and so does everything downstream.

    Compares against the vendored kernel on the real L21 block. Returns
    the number of differing scales. */
std::size_t saturation_verify(state *s, int const depth) {

    if (s == nullptr)
        return 1;

    int const n   = static_cast<int>(s->n);
    int const b   = (n < 256)? n : 256;
    int const r0  = b;
    int const mp  = n - r0;
    if (mp <= 0)
        return 1;

    std::int8_t *lq = nullptr;
    float       *ls = nullptr, *sc = nullptr;
    int         *d_last = nullptr, *d_uf = nullptr;
    float       *d_g = nullptr;
    CUDA_CHECK(cudaMalloc(&lq, static_cast<std::size_t>(depth) * mp * b));
    CUDA_CHECK(cudaMalloc(&ls, static_cast<std::size_t>(depth) * mp * sizeof(float)));
    CUDA_CHECK(cudaMalloc(&sc, static_cast<std::size_t>(depth) * n * sizeof(float)));
    CUDA_CHECK(cudaMalloc(&d_last, n * sizeof(int)));
    CUDA_CHECK(cudaMalloc(&d_uf, n * sizeof(int)));
    CUDA_CHECK(cudaMalloc(&d_g, 2 * QLU_I0MAX * n * sizeof(float)));

    /*  The vendored slicer, on exactly the block the trailing update
        slices: rows [b, n) over columns [0, b). */
    LAUNCH((k_slice_rows<<<mp, 256>>>(n, r0, 0, mp, b, depth,
                                      s->d_hi, s->d_lo, lq, ls)));

    k_saturation<<<n, 256>>>(n, 0, b, depth, 127, s->d_hi, s->d_lo,
                             d_last, d_uf, d_g, nullptr, sc);
    KERNEL_CHECK();

    std::vector<float> h_ls(static_cast<std::size_t>(depth) * mp);
    std::vector<float> h_sc(static_cast<std::size_t>(depth) * n);
    CUDA_CHECK(cudaMemcpy(h_ls.data(), ls, h_ls.size() * sizeof(float),
                          cudaMemcpyDeviceToHost));
    CUDA_CHECK(cudaMemcpy(h_sc.data(), sc, h_sc.size() * sizeof(float),
                          cudaMemcpyDeviceToHost));

    std::size_t bad = 0;
    for (int lev = 0; lev != depth; ++lev)
        for (int i = 0; i != mp; ++i) {
            float const v = h_ls[static_cast<std::size_t>(lev) * mp + i];
            float const w = h_sc[static_cast<std::size_t>(lev) * n + r0 + i];
            if (v != w)
                ++bad;
        }

    cudaFree(lq); cudaFree(ls); cudaFree(sc);
    cudaFree(d_last); cudaFree(d_uf); cudaFree(d_g);
    return bad;
}

/*  Select the slicer's rounding mode for every subsequent factor.

    Global rather than per-state because the slicer is vendored and the
    flag lives beside it; there is one device symbol and it applies to
    whatever factors next. Calls are cheap and the gates set it
    explicitly on both sides rather than relying on the default. */
/*  Apply the preconditioner B_0^-1 = U^-1 L^-1 P once, through the
    SAME DF32 triangular-solve path refinement uses.

    The point is that rho(M) measured from a dumped factor is a property
    of the dumped operator, not of the one the solve applies. Those can
    differ by a few percent, and a few percent is decisive when the
    eigenvalue sits at 0.524 against a threshold of 0.5. This gives
    Mv = Ahat^-1(Av) - v on the REALIZED operator, so the spectral radius
    that governs the iteration can be measured directly -- and it is the
    same operator-access trick that makes this tractable at large n,
    where forming M is out of the question. */
void apply_inverse(state *s, double *d_out, double const *d_in) {

    if (s == nullptr)
        return;

    int const  n  = static_cast<int>(s->n);
    int const  T  = 256;
    int const  g  = (n + T - 1) / T;
    std::size_t const ld = s->n;

    LAUNCH((k_split_f64<<<g, T>>>(n, d_in, s->d_rh, s->d_rl)));
    LAUNCH((gather_kernel<<<g, T>>>(n, s->d_perm, s->d_rh, s->d_rl,
                                    s->d_yh, s->d_yl)));
    if (s->srung_ib != 0) {
        trsv_L_mrhs(n, 256, s->srung_ib, 1, (int)ld,
                    s->d_hi, s->d_lo, s->d_dlh, s->d_dll,
                    s->d_yh, s->d_yl, s->d_zh, s->d_zl,
                    s->d_th, s->d_tl);
        trsv_U_mrhs(n, 256, s->srung_ib, 1, (int)ld,
                    s->d_hi, s->d_lo, s->d_duh, s->d_dul,
                    s->d_zh, s->d_zl, s->d_yh, s->d_yl,
                    s->d_th, s->d_tl);
    } else {
        trsv_L_blocked(n, 256, s->d_hi, s->d_lo, s->d_yh, s->d_yl,
                       s->d_zh, s->d_zl, s->d_th, s->d_tl);
        trsv_U_blocked(n, 256, s->d_hi, s->d_lo, s->d_zh, s->d_zl,
                       s->d_yh, s->d_yl, s->d_th, s->d_tl);
    }
    LAUNCH((combine_kernel<<<g, T>>>(n, s->d_yh, s->d_yl, d_out)));
    CUDA_CHECK(cudaDeviceSynchronize());
}

