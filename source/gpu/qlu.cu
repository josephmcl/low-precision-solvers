struct state {

    std::size_t    n       = 0;
    int            b       = 0;
    int            kfac    = 0;
    kernel         which   = kernel::sliced;
    oii::state    *oii_s   = nullptr;

    /*  S-rung diagonal-block inverses, n*IB floats each, built once per
        factorization. Null when srung_ib is 0. */
    int    srung_ib = 0;
    float *d_dlh = nullptr, *d_dll = nullptr;
    float *d_duh = nullptr, *d_dul = nullptr;
    cublasHandle_t blas    = nullptr;
    Int8LUScratch  scratch = {};

    /*  Residual operator and carrier, both row-major DF32. Distinct because
        the factorization consumes the carrier. */
    float *d_ah = nullptr, *d_al = nullptr;
    float *d_hi = nullptr, *d_lo = nullptr;

    int *d_piv  = nullptr;   /* getrf-style interchanges                 */
    int *d_forced = nullptr; /* A3 forced interchange sequence           */
    int  last_refactor_requested = 0;   /* A2: hook ended the solve */
    int    last_converged = 0;          /* every column met the residual test */
    double last_rel       = 0.;         /* worst column's last normalised residual */
    int *d_perm = nullptr;   /* composed permutation, host-built         */

    /*  Solve workspace. */
    std::size_t rhs_cap = 0;     /* columns the solve workspace holds */

    /*  GMRES-IR workspace: the Arnoldi basis (j+1 blocks of n x k), the
        Hessenberg store, and the small per-column scalars. Allocated on
        first use at a given (j, k). */
    int    gm_j = 0;
    std::size_t gm_k = 0;
    float *gm_vh = nullptr, *gm_vl = nullptr;   /* (j+1) * n * k */
    float *gm_wh = nullptr, *gm_wl = nullptr;   /* n * k         */
    float *gm_th = nullptr, *gm_tl = nullptr;   /* n * k scratch */
    float *gm_uh = nullptr, *gm_ul = nullptr;   /* n * k scratch */
    float *gm_hh = nullptr, *gm_hl = nullptr;   /* k*(j+1)*j     */
    float *gm_yh = nullptr, *gm_yl = nullptr;   /* k*j           */
    float *gm_sh = nullptr, *gm_sl = nullptr;   /* k scalars     */
    float *gm_bh = nullptr, *gm_bl = nullptr;   /* k betas       */
    int   *gm_keff = nullptr;                   /* k             */
    float *d_bh = nullptr, *d_bl = nullptr;
    float *d_xh = nullptr, *d_xl = nullptr;
    float *d_rh = nullptr, *d_rl = nullptr;
    float *d_yh = nullptr, *d_yl = nullptr;
    float *d_zh = nullptr, *d_zl = nullptr;
    float *d_th = nullptr, *d_tl = nullptr;
    float *d_nrm = nullptr;
    double a_inf  = 0.;    /* ||A||_inf, for a conditioning-free metric */
    double last_rho = 0.;  /* ||d_{k+1}||/||d_k||, the rho(M) estimate */
    int    last_diverged = 0;

    std::vector<void *> owned;

    /*  Phase markers. One event per boundary, synchronized once at the end,
        so the breakdown costs a record per phase and no serialization. */
    std::vector<cudaEvent_t> marks;
    std::size_t              n_marks = 0;
    phase_times              times   = {};

    /*  Phase each span ENDS in; -1 opens the sequence. Tagging rather than
        assuming a fixed stride per iteration, because the loop can exit at
        the convergence test with only part of an iteration recorded. */
    std::vector<int> tags;

    cudaEvent_t mark(int const phase) {
        if (n_marks < tags.size()) tags[n_marks] = phase;
        else                       tags.push_back(phase);
        if (n_marks == marks.size()) {
            cudaEvent_t e = nullptr;
            CUDA_CHECK(cudaEventCreate(&e));
            marks.push_back(e);
        }
        cudaEvent_t const e = marks[n_marks++];
        CUDA_CHECK(cudaEventRecord(e));
        return e;
    }

    /*  Sum the spans by tag. Call after a synchronization. */
    void fold(double *bucket[]) {
        for (std::size_t i = 1; i != n_marks; ++i)
            if (tags[i] >= 0)
                *bucket[tags[i]] += span(i - 1, i);
        n_marks = 0;
    }

    double span(std::size_t const a, std::size_t const b) const {
        float ms = 0.f;
        CUDA_CHECK(cudaEventElapsedTime(&ms, marks[a], marks[b]));
        return static_cast<double>(ms);
    }

    void *acquire(std::size_t const bytes) {
        void *p = nullptr;
        if (!CUDA_CHECK(cudaMalloc(&p, bytes)))
            return nullptr;
        owned.push_back(p);
        return p;
    }
};

void select_panel_variant();        /*  defined below, called from create because the
                                        vendored allocator reads FLAG */

state *create(
    std::size_t const n,
    int const         b,
    int const         kfac,
    kernel const      which,
    int const         srung_ib) {

    if (srung_ib != 0 && (srung_ib <= 0 || n % srung_ib != 0)) {
        std::fprintf(stderr, "[qlu] srung_ib=%d does not divide n=%zu\n",
                     srung_ib, n);
        return nullptr;
    }

    /*  CLAMP THE PANEL WIDTH BEFORE ANYTHING ALLOCATES.

        int8lu_scratch_alloc computes `size_t M = (size_t)(n - b)` from
        two ints. With b > n that is negative, wraps to about 2^64, and
        the cudaMalloc that follows asks for a nonsense size. Upstream
        never sees it because int8lu_factor clamps `if(b<=0||b>n) b=n`
        -- but that clamp is inside the FACTOR, which runs long after
        the scratch is allocated, so the wrapper has to do it here.

        Found by a boundary test in lps-consistency, which triggered it
        rather than reporting it: the machine became unreachable during
        the run. The clamp matches the vendor's own rule so the
        factorization behaves identically; what changes is that the
        allocation is sane. */
    /*  LPS_SR=1 selects keyed stochastic rounding for every arm in the
        process, matching how FUSE/ASYNC and the rest of this codebase's
        knobs are set. Read here so a binary that never heard of the
        flag still honours it; explicit set_rounding calls override it
        and the gates use those. */
    {
        static bool once = false;
        if (!once) {
            once = true;
            char const *e = std::getenv("LPS_SR");
            if (e != nullptr && e[0] == '1')
                set_rounding(rounding::stochastic);
        }
    }

    int b_use = b;
    if (b_use <= 0 || static_cast<std::size_t>(b_use) > n)
        b_use = static_cast<int>(n);

    state *s = new state;
    s->n        = n;
    s->b        = b_use;
    s->kfac     = kfac;
    s->which    = which;
    s->srung_ib = srung_ib;

    if (!CUBLAS_CHECK(cublasCreate(&s->blas))) {
        delete s;
        return nullptr;
    }

    std::size_t const nn = n * n;
    s->d_ah = static_cast<float *>(s->acquire(nn * sizeof(float)));
    s->d_al = static_cast<float *>(s->acquire(nn * sizeof(float)));
    s->d_hi = static_cast<float *>(s->acquire(nn * sizeof(float)));
    s->d_lo = static_cast<float *>(s->acquire(nn * sizeof(float)));

    s->d_piv  = static_cast<int *>(s->acquire(n * sizeof(int)));
    s->d_perm = static_cast<int *>(s->acquire(n * sizeof(int)));

    float **const work[] = {&s->d_bh, &s->d_bl, &s->d_xh, &s->d_xl,
                            &s->d_rh, &s->d_rl, &s->d_yh, &s->d_yl,
                            &s->d_zh, &s->d_zl, &s->d_th, &s->d_tl};
    for (std::size_t i = 0; i != sizeof work / sizeof *work; ++i)
        *work[i] = static_cast<float *>(s->acquire(n * sizeof(float)));

    s->d_nrm = static_cast<float *>(s->acquire(sizeof(float)));

    if (srung_ib != 0) {
        std::size_t const nb = n * static_cast<std::size_t>(srung_ib)
                             * sizeof(float);
        s->d_dlh = static_cast<float *>(s->acquire(nb));
        s->d_dll = static_cast<float *>(s->acquire(nb));
        s->d_duh = static_cast<float *>(s->acquire(nb));
        s->d_dul = static_cast<float *>(s->acquire(nb));
        if (s->d_dul == nullptr) {
            destroy(s);
            return nullptr;
        }
    }

    /*  Before the scratch, not before the factor: the vendored allocator reads
        FLAG itself and sizes the panel's buffers from it. */
    select_panel_variant();
    int8lu_scratch_alloc(s->scratch, static_cast<int>(n), b_use, kfac);

    if (which == kernel::oii) {
        /*  Sized for the first trailing update, which is the largest;
            every later one is smaller and passes its own m and n.

            n <= b means the whole matrix is one panel and there is no
            trailing update at all. Guarded because `n - b` is computed
            in size_t and would wrap to an enormous allocation rather
            than fail. */
        if (n <= static_cast<std::size_t>(b_use)) {
            std::fprintf(stderr, "[qlu] oii arm needs n > b "
                                 "(n=%zu b=%d): no trailing update\n",
                         n, b_use);
            destroy(s);
            return nullptr;
        }
        s->oii_s = oii::create(n - static_cast<std::size_t>(b_use), b_use,
                               n - static_cast<std::size_t>(b_use), kfac);
        if (s->oii_s == nullptr) {
            destroy(s);
            return nullptr;
        }
    }
    return s;
}

void destroy(state *s) {

    if (s == nullptr)
        return;

    oii::destroy(s->oii_s);

    for (std::size_t i = 0; i != s->marks.size(); ++i)
        CUDA_CHECK(cudaEventDestroy(s->marks[i]));

    int8lu_scratch_free(s->scratch);
    for (std::size_t i = 0; i != s->owned.size(); ++i)
        CUDA_CHECK(cudaFree(s->owned[i]));
    if (s->blas != nullptr)
        CUBLAS_CHECK(cublasDestroy(s->blas));

    delete s;
}

void prepare(
    state        *s,
    double const *d_a) {

    if (s == nullptr)
        return;

    std::size_t const nn = s->n * s->n;

    /*  One transpose+split into the residual operator, then a straight copy
        into the carrier: the two hold the same matrix and only the carrier
        is destroyed. */
    s->times = phase_times();
    s->n_marks = 0;
    s->mark(-1);

    convert::transpose_split_df32(s->d_ah, s->d_al, d_a, s->n);
    CUDA_CHECK(cudaMemcpy(s->d_hi, s->d_ah, nn * sizeof(float),
                          cudaMemcpyDeviceToDevice));
    CUDA_CHECK(cudaMemcpy(s->d_lo, s->d_al, nn * sizeof(float),
                          cudaMemcpyDeviceToDevice));

    s->mark(0);
    CUDA_CHECK(cudaDeviceSynchronize());
    s->times.prepare += s->span(0, 1);
    s->n_marks = 0;
}

/*  ---- GMRES-IR(j) ----------------------------------------------------

    Outer refinement whose correction equation A d = r is solved by j
    GMRES steps, LEFT-preconditioned by B0^-1 = U^-1 L^-1 P, from x0 = 0.
    That is the setting of the core's outer-step theorem, and it matches
    core_exp/ir.py::gmres_ir, which is the reference this is gated
    against.

    WHY THE BATCHED TRSM WAS A PREREQUISITE. Arnoldi steps are
    sequentially dependent: step i+1 needs the vector step i produced, so
    there is nothing to batch WITHIN one system's inner solve. What
    batches is step i of all k right-hand sides, which is one call to
    trsv_*_mrhs over k columns. Without that, GMRES-IR(j) on k systems
    costs j*k triangular solves; with it, j.

    Everything is DF32. The (j+1) x j least squares runs on the device,
    one thread per column -- j <= 8, so the work is nothing, and keeping
    it there avoids an fp64 island on the host and a sync inside the
    Arnoldi loop. */

/*  DF32 square root: one Newton step on the fp32 seed, which takes ~24
    bits to ~48 and is what the pair holds. */
__device__ __forceinline__ df32 df_sqrt(df32 const a) {

    if (a.hi <= 0.f)
        return df_make(0.f, 0.f);
    float const r0 = sqrtf(a.hi);
    df32 const q = df_div(a, df_make(r0, 0.f));
    df32 const s = df_add_acc(df_make(r0, 0.f), q);
    return df_mul(s, df_make(0.5f, 0.f));
}

/*  Elementwise DF32 sqrt of k scalars. */
__global__ void k_df_sqrt_scalars(
    int const nrhs, float const *ih, float const *il,
    float *oh, float *ol) {

    int const c = blockIdx.x * blockDim.x + threadIdx.x;
    if (c >= nrhs)
        return;
    df32 const r = df_sqrt(df_make(ih[c], il[c]));
    oh[c] = r.hi;
    ol[c] = r.lo;
}

/*  y += Y[c*j + i] * x, the coefficient taken from the least squares. */
__global__ void k_df_axpy_strided(
    int const n, int const nrhs, int const ld, int const j, int const i,
    float const *ch, float const *cl,
    float const *xh, float const *xl,
    float *yh, float *yl) {

    int const q = blockIdx.x * blockDim.x + threadIdx.x;
    int const c = blockIdx.y;
    if (q >= n || c >= nrhs)
        return;
    std::size_t const o = static_cast<std::size_t>(c) * ld + q;
    std::size_t const e = static_cast<std::size_t>(c) * j + i;
    df32 const r = df_add_acc(df_make(yh[o], yl[o]),
                              df_mul(df_make(ch[e], cl[e]),
                                     df_make(xh[o], xl[o])));
    yh[o] = r.hi;
    yl[o] = r.lo;
}

/*  Deterministic DF32 dot per column: one block, fixed-order tree, so
    the result does not depend on how the blocks happened to schedule.
    Reproducibility is the reason the vendored reductions are written
    this way and the reason this one is too. */
__global__ void k_df_dot_mrhs(
    int const    n,
    int const    ld,
    float const *xh,
    float const *xl,
    float const *yh,
    float const *yl,
    float       *oh,
    float       *ol) {

    __shared__ float sh[256], sl[256];
    std::size_t const off = static_cast<std::size_t>(blockIdx.x) * ld;
    int const t = threadIdx.x;

    df32 acc = df_make(0.f, 0.f);
    for (int i = t; i < n; i += blockDim.x)
        acc = df_add_acc(acc, df_mul(df_make(xh[off + i], xl[off + i]),
                                     df_make(yh[off + i], yl[off + i])));
    sh[t] = acc.hi;
    sl[t] = acc.lo;
    __syncthreads();
    for (int o = blockDim.x >> 1; o > 0; o >>= 1) {
        if (t < o) {
            df32 const v = df_add_acc(df_make(sh[t], sl[t]),
                                      df_make(sh[t + o], sl[t + o]));
            sh[t] = v.hi;
            sl[t] = v.lo;
        }
        __syncthreads();
    }
    if (t == 0) {
        oh[blockIdx.x] = sh[0];
        ol[blockIdx.x] = sl[0];
    }
}

/*  y += s * a[col] * x, the scalar read from device so the Arnoldi loop
    never synchronizes. */
__global__ void k_df_axpy_mrhs(
    int const    n,
    int const    nrhs,
    int const    ld,
    float const  s,
    float const *ah,
    float const *al,
    float const *xh,
    float const *xl,
    float       *yh,
    float       *yl) {

    int const i = blockIdx.x * blockDim.x + threadIdx.x;
    int const c = blockIdx.y;
    if (i >= n || c >= nrhs)
        return;
    std::size_t const o = static_cast<std::size_t>(c) * ld + i;
    df32 const a = df_mul(df_make(ah[c], al[c]), df_make(s, 0.f));
    df32 const r = df_add_acc(df_make(yh[o], yl[o]),
                              df_mul(a, df_make(xh[o], xl[o])));
    yh[o] = r.hi;
    yl[o] = r.lo;
}

/*  v = x / a[col], with a zero-ish divisor left as an exact zero vector:
    that is a happy breakdown, and the least squares below is told how
    many columns are real via `keff`. */
__global__ void k_df_normalize_mrhs(
    int const    n,
    int const    nrhs,
    int const    ld,
    int const    step,
    float const *nh,
    float const *nl,
    float const *bh,
    float       *xh,
    float       *xl,
    int         *keff) {

    int const i = blockIdx.x * blockDim.x + threadIdx.x;
    int const c = blockIdx.y;
    if (i >= n || c >= nrhs)
        return;
    std::size_t const o = static_cast<std::size_t>(c) * ld + i;

    float const nrm = nh[c];
    if (!(nrm > 1e-14f * bh[c])) {
        xh[o] = 0.f;
        xl[o] = 0.f;
        if (i == 0)
            atomicMin(&keff[c], step);
        return;
    }
    df32 const r = df_div(df_make(xh[o], xl[o]), df_make(nh[c], nl[c]));
    xh[o] = r.hi;
    xl[o] = r.lo;
}

/*  Least squares min || H y - beta e1 || by Givens, one thread per
    column. H is (j+1) x j, stored column major per right-hand side. */
__global__ void k_gmres_lsq(
    int const    j,
    int const    nrhs,
    float const *hh,
    float const *hl,
    float const *bh,
    float const *bl,
    int const   *keff,
    float       *yh,
    float       *yl) {

    int const c = blockIdx.x * blockDim.x + threadIdx.x;
    if (c >= nrhs)
        return;

    int const k = (keff[c] < j)? keff[c] : j;
    std::size_t const hb = static_cast<std::size_t>(c) * (j + 1) * j;

    df32 r[9][8];                 /* (j+1) x j, j <= 8 */
    df32 g[9];
    for (int a = 0; a <= k; ++a) {
        g[a] = df_make(0.f, 0.f);
        for (int b = 0; b < k; ++b)
            r[a][b] = df_make(hh[hb + static_cast<std::size_t>(b) * (j + 1) + a],
                              hl[hb + static_cast<std::size_t>(b) * (j + 1) + a]);
    }
    g[0] = df_make(bh[c], bl[c]);

    for (int b = 0; b < k; ++b) {
        df32 const a1 = r[b][b], a2 = r[b + 1][b];
        df32 const d = df_sqrt(df_add_acc(df_mul(a1, a1), df_mul(a2, a2)));
        if (!(d.hi > 0.f))
            continue;
        df32 const cs = df_div(a1, d), sn = df_div(a2, d);
        for (int q = b; q < k; ++q) {
            df32 const t1 = r[b][q], t2 = r[b + 1][q];
            r[b][q]     = df_add_acc(df_mul(cs, t1), df_mul(sn, t2));
            r[b + 1][q] = df_sub_acc(df_mul(cs, t2), df_mul(sn, t1));
        }
        df32 const t1 = g[b], t2 = g[b + 1];
        g[b]     = df_add_acc(df_mul(cs, t1), df_mul(sn, t2));
        g[b + 1] = df_sub_acc(df_mul(cs, t2), df_mul(sn, t1));
    }

    for (int b = k - 1; b >= 0; --b) {
        df32 acc = g[b];
        for (int q = b + 1; q < k; ++q)
            acc = df_sub_acc(acc, df_mul(r[b][q],
                                         df_make(yh[static_cast<std::size_t>(c) * j + q],
                                                 yl[static_cast<std::size_t>(c) * j + q])));
        df32 const v = (r[b][b].hi != 0.f)? df_div(acc, r[b][b])
                                          : df_make(0.f, 0.f);
        yh[static_cast<std::size_t>(c) * j + b] = v.hi;
        yl[static_cast<std::size_t>(c) * j + b] = v.lo;
    }
    for (int b = k; b < j; ++b) {
        yh[static_cast<std::size_t>(c) * j + b] = 0.f;
        yl[static_cast<std::size_t>(c) * j + b] = 0.f;
    }
}

/*  Scatter one column of H, produced as a per-column dot, into the
    Hessenberg store, accumulating (MGS with reorthogonalization adds to
    the same entry twice). */
__global__ void k_h_accum(
    int const    nrhs,
    int const    j,
    int const    row,
    int const    col,
    float const *vh,
    float const *vl,
    float       *hh,
    float       *hl) {

    int const c = blockIdx.x * blockDim.x + threadIdx.x;
    if (c >= nrhs)
        return;
    std::size_t const o = static_cast<std::size_t>(c) * (j + 1) * j
                        + static_cast<std::size_t>(col) * (j + 1) + row;
    df32 const r = df_add_acc(df_make(hh[o], hl[o]),
                              df_make(vh[c], vl[c]));
    hh[o] = r.hi;
    hl[o] = r.lo;
}

/*  DF32 matvec over k columns: one warp per (row, right-hand side), with
    consecutive warps on the same row so the row of A is fetched once and
    serves all k -- the same amortization the batched TRSV uses. */
__global__ void k_df_matvec_mrhs(
    int const    n,
    int const    nrhs,
    int const    ld,
    float const *ah,
    float const *al,
    float const *xh,
    float const *xl,
    float       *yh,
    float       *yl) {

    int const gw   = (blockIdx.x * blockDim.x + threadIdx.x) >> 5;
    int const lane = threadIdx.x & 31;
    if (gw >= n * nrhs)
        return;
    int const r = gw / nrhs;
    std::size_t const off = static_cast<std::size_t>(gw % nrhs) * ld;

    df32 acc = df_make(0.f, 0.f);
    for (int q = lane; q < n; q += 32)
        acc = df_add_acc(acc, df_mul(
            df_make(ah[static_cast<std::size_t>(r) * n + q],
                    al[static_cast<std::size_t>(r) * n + q]),
            df_make(xh[off + q], xl[off + q])));
    for (int o = 16; o > 0; o >>= 1) {
        float const oh = __shfl_down_sync(0xffffffffu, acc.hi, o);
        float const ol = __shfl_down_sync(0xffffffffu, acc.lo, o);
        acc = df_add_acc(acc, df_make(oh, ol));
    }
    if (lane == 0) {
        yh[off + r] = acc.hi;
        yl[off + r] = acc.lo;
    }
}

/*  ---- slice-cascade saturation on the production carrier -------------

    i_sat is the level at which the DF32 accumulator stops changing BITS.
    Not a chi criterion, not a residual threshold: the thing itself.

    This replicates k_slice_rows exactly -- per-row max over |hi|, scale
    max/127, rintf, clamp to +-127, exact two_prod, and the residual
    updated with df_sub_acc -- and adds a change detector on the
    accumulator. Replicating rather than calling it is deliberate: the
    vendored kernel writes slices and scales and keeps no accumulator,
    and the numerics here are line-for-line the same.

    The carrier has to govern the WHOLE cascade, residual included. The
    simulation measured what happens otherwise: with the slicer left in
    fp64 and only the accumulator widened, i_sat ran past 24 levels
    against a predicted 17, because the contributions floored at
    u * rowmax instead of continuing to shrink geometrically. Here the
    residual is DF32 because the arm's residual is DF32.

    The segment width is the panel's 256-column k-extent, because that is
    the extent the trailing update actually slices over. Saturation
    depends on the dynamic range the scale has to cover, so measuring it
    over a different extent would measure a different quantity. */
__global__ void k_saturation(
    int const    n,
    int const    c0,
    int const    width,
    int const    max_depth,
    int const    qmax,          /* beta = 2*qmax: 7 -> 14, 31 -> 62, 127 -> 254 */
    float const *ah,
    float const *al,
    int         *last_change,
    int         *uf_level,
    float       *g_ratio,
    int         *isat_i0,       /* optional, QLU_I0MAX x n */
    float       *scale_out) {   /* optional, depth x n */

    /*  Sized for the only launch configuration this kernel has, 256
        threads; the reductions below read blockDim.x so they stay
        correct if that changes, but these arrays would not. */
    __shared__ float rh[256], rl[256], acch[256], accl[256], red[256];
    __shared__ float gmx[256];
    __shared__ int   any;

    /*  cor:absorbgeo reads Gamma = max_{(r,s) in I} C_rs / m_rs, where
        |delta^(i)_rs| <= C_rs beta^-i and m_rs is a floor on |a^(i)_rs|
        holding for ALL i >= i_0. Two things follow that the first
        version of this kernel got wrong.

        First, the ratio pairs the largest contribution with the SMALLEST
        accumulator over the tail, not with the accumulator that happened
        to be there at the same level. Dividing by the running |a^(i-1)|
        gives max_i (C_i / a_{i-1}), which is bounded above by
        (max_i C_i) / (min_i a_i) and equals it only when the accumulator
        never shrinks. So the old reading under-estimates Gamma wherever
        the accumulator cancels later -- the direction that leaves rows
        above i*.

        Second, i_0 is part of the statement and is measured, not
        assumed: the index set is entries that stay nonzero from i_0 on,
        so an entry that revives after a zero is outside I for small i_0
        and inside it for larger. Sweeping i_0 is what the core's remark
        means by the startup index being operational -- the within-family
        trends collapse once it is taken from the data. */
    float cmax[QLU_I0MAX], mmin[QLU_I0MAX];
    bool  live[QLU_I0MAX];
    for (int k = 0; k != QLU_I0MAX; ++k) {
        cmax[k] = -1e30f;
        mmin[k] =  1e30f;
        live[k] = true;
    }

    int const i = blockIdx.x;
    int const t = threadIdx.x;

    float const v_h = (t < width)? ah[static_cast<std::size_t>(i) * n + c0 + t] : 0.f;
    float const v_l = (t < width)? al[static_cast<std::size_t>(i) * n + c0 + t] : 0.f;
    rh[t] = v_h;
    rl[t] = v_l;
    acch[t] = 0.f;
    accl[t] = 0.f;
    gmx[t]  = -1e30f;
    int last = 0;
    int uf   = 0;
    /*  Per-ENTRY last change. `last` below is the row-level OR, which is
        what i_sat has always meant here; this is the finer quantity the
        corollary needs, because the index set I excludes entries rather
        than rows. */
    int last_e = 0;

    /*  And the level at which lem:absorb's own criterion last failed.

        These are different quantities and conflating them is what made
        eps_sat read 11.9. `last_e` is bit-identity of the DF32 PAIR,
        which is what i_sat has always meant here and is the right
        thing for the depth dial: it answers "does another slice change
        the stored value". But lem:absorb is stated for "a
        fixed-precision binary carrier with unit roundoff u_c, with
        underflow and subnormals excluded", and an unevaluated
        two-float pair is not one. Its low word can absorb increments
        far below (u_c/2)|a| without the pair being bit-identical, so
        the pair keeps recording changes for levels after a genuine
        49-bit carrier would have stopped -- 18 rather than 8 on the
        worst U12 entries.

        cor:absorbgeo bounds the lemma's depth, so the lemma's
        criterion is what it has to be measured against:
        fl(a + delta) = a once |delta| < rad_c(a), and
        rad_c(a) >= (u_c/2)|a| is the carrier-independent sufficient
        form the lemma gives. */
    int last_abs = 0;

    /*  The radix is a parameter because the core registers the carrier
        translation law across beta in {14, 62, 254}, and a single radix
        tests one point of that sweep. beta = 2*qmax: the slice is
        rounded to +-qmax, so one level buys a factor of 2*qmax. */
    float const fq    = static_cast<float>(qmax);
    float const lbeta = __logf(2.f * fq);
    __syncthreads();

    for (int s = 1; s <= max_depth; ++s) {

        float m = (t < width)? fabsf(rh[t]) : 0.f;
        red[t] = m;
        __syncthreads();
        for (int o = blockDim.x >> 1; o > 0; o >>= 1) {
            if (t < o)
                red[t] = fmaxf(red[t], red[t + o]);
            __syncthreads();
        }

        float sc = (red[0] > 0.f)? red[0] / fq : 1.f;
        /*  The residual reaches the denormal floor and the scale flushes
            to zero long before a fixed depth cap is hit; the division
            would then poison the whole cascade with inf. Guarded, and
            the fact that it happened is REPORTED rather than swallowed,
            because a run that underflowed is measuring the exponent
            range and not the saturation depth. */
        /*  The residual has reached the denormal floor: there is nothing
            left to slice, and the division would poison the cascade with
            inf. Record WHEN it happened per row rather than raising one
            global flag -- a row whose residual vanished has saturated,
            and only underflow BEFORE the last change invalidates the
            measurement. The first version flagged the whole grid on any
            row underflowing and reported nothing usable. */
        if (sc == 0.f) {
            sc = 1.f;
            if (uf == 0)
                uf = s;
        }

        if (t == 0) {
            any = 0;
            if (scale_out != nullptr)
                scale_out[static_cast<std::size_t>(s - 1) * gridDim.x + i]
                    = sc;
        }
        __syncthreads();

        if (t < width) {
            float q = rintf(rh[t] / sc);
            q = fminf(fmaxf(q, -fq), fq);
            df32 const x    = two_prod(sc, q);
            df32 const prev = df_make(acch[t], accl[t]);
            df32 const a    = df_add_acc(prev, x);
            if (a.hi != prev.hi || a.lo != prev.lo) {
                atomicOr(&any, 1);
                last_e = s;
            }
            /*  U_C/2 = 2^-50. Against the PRE-update magnitude, which
                is the `a` of the lemma's fl(a + delta). */
            float const pv_abs = fabsf(prev.hi + prev.lo);
            if (fabsf(x.hi + x.lo) >= 0x1p-50f * pv_abs)
                last_abs = s;

            /*  Kept in LOG space throughout. Forming the ratio times
                beta^i and taking the log afterwards overflows fp32 at
                i = 16 -- beta^16 is 1e38 -- and reports inf for every
                cell, which is what the first version did. */
            float const av = fabsf(a.hi + a.lo);
            float const xv = fabsf(x.hi + x.lo);
            float const lx = (xv > 0.f)? __logf(xv) / lbeta : -1e30f;
            float const la = (av > 0.f)? __logf(av) / lbeta :  1e30f;

            for (int k = 0; k != QLU_I0MAX; ++k) {
                if (s < k + 1)
                    continue;
                if (av <= 0.f) {
                    /*  m_rs > 0 is a hypothesis of the corollary, so an
                        entry that is zero anywhere from i_0 on is simply
                        not in I at that i_0. */
                    live[k] = false;
                    continue;
                }
                if (xv > 0.f)
                    cmax[k] = fmaxf(cmax[k], lx + (float)s);
                mmin[k] = fminf(mmin[k], la);
            }

            acch[t] = a.hi;
            accl[t] = a.lo;
            df32 const r = df_sub_acc(df_make(rh[t], rl[t]), x);
            rh[t] = r.hi;
            rl[t] = r.lo;
        }
        __syncthreads();

        if (any != 0)
            last = s;
    }

    /*  Row maxima of the Gamma reading, one per candidate i_0. The max
        over entries of (cmax - mmin) is taken per entry first: the max
        of a difference is not the difference of the extremes. */
    for (int k = 0; k != QLU_I0MAX; ++k) {
        __syncthreads();
        gmx[t] = (t < width && live[k] && cmax[k] > -1e29f)?
                     cmax[k] - mmin[k] : -1e30f;
        __syncthreads();
        for (int o = blockDim.x >> 1; o > 0; o >>= 1) {
            if (t < o)
                gmx[t] = fmaxf(gmx[t], gmx[t + o]);
            __syncthreads();
        }
        if (t == 0)
            g_ratio[static_cast<std::size_t>(k) * gridDim.x + i] = gmx[0];

        /*  i_sat over the SAME index set that produced g(i_0).

            Reduced as the max of the PER-ENTRY slack, not as a max of
            i_sat to be differenced against a max of g afterwards. Those
            are maxima over different entries, and subtracting them is
            not a bound on anything: it read 9.8 for U12 while the
            block's g was 3, which is arithmetically impossible for a
            single entry and was an artifact of the pairing. The
            corollary is a per-entry statement, so the slack is formed
            per entry and the worst one is what gets reported. */
        if (isat_i0 != nullptr) {
            __syncthreads();
            bool const in_I = (t < width && live[k] && cmax[k] > -1e29f);
            red[t] = in_I? static_cast<float>(last_e) : -1.f;
            __syncthreads();
            for (int o = blockDim.x >> 1; o > 0; o >>= 1) {
                if (t < o)
                    red[t] = fmaxf(red[t], red[t + o]);
                __syncthreads();
            }
            if (t == 0)
                isat_i0[static_cast<std::size_t>(k) * gridDim.x + i] =
                    (red[0] < 0.f)? -1 : static_cast<int>(red[0]) + 1;

            /*  eps_entry = i_sat_entry - g_entry - log_beta(1/u_c),
                stashed in the upper half of g_ratio. */
            __syncthreads();
            gmx[t] = in_I? (static_cast<float>(last_abs + 1)
                            - (cmax[k] - mmin[k])
                            - (49.f * 0.693147f / lbeta)) : -1e30f;
            __syncthreads();
            for (int o = blockDim.x >> 1; o > 0; o >>= 1) {
                if (t < o)
                    gmx[t] = fmaxf(gmx[t], gmx[t + o]);
                __syncthreads();
            }
            if (t == 0)
                g_ratio[static_cast<std::size_t>(QLU_I0MAX + k) * gridDim.x + i]
                    = gmx[0];
        }
    }

    if (t == 0) {
        last_change[i] = last;
        uf_level[i]    = uf;
    }
}

/*  ---- multi-RHS triangular solve -------------------------------------

    The solve was a loop over columns: k right-hand sides cost k
    independent chains and the measured per-RHS time was flat at 19.35 ms
    from k=1 to k=16, i.e. no amortization at all. The phase split at k=16
    says where it all is -- TRSV 97.5 percent, residual 2.0, gather 0.2,
    update 0.3 -- so these two kernel pairs are the whole job and the
    residual stays per column.

    Each column's arithmetic is UNCHANGED: same loop bounds, same warp
    reduction order, same sub-block sequence. The batched path is
    therefore bit-identical to the column loop, which is what the gate
    checks. The win is not arithmetic, it is that one pass over L\U now
    serves k columns and that the diagonal apply, which ran in a SINGLE
    block, now runs in k.

    Vectors are n x nrhs, column major with stride ldv, so a single-vector
    kernel still works on any one column by pointer offset. */

/*  Off-diagonal update, one warp per (row, rhs). Consecutive warps take
    the same row across right-hand sides, so the row of L\U is fetched
    once and serves all of them. */
__global__ void k_trsv_off_L_mrhs(
    int const    n,
    int const    i0,
    int const    ni,
    int const    nrhs,
    int const    ldv,
    float const *luh,
    float const *lul,
    float const *yh,
    float const *yl,
    float const *bh,
    float const *bl,
    float       *rh,
    float       *rl) {

    int const gw   = (blockIdx.x * blockDim.x + threadIdx.x) >> 5;
    int const lane = threadIdx.x & 31;
    if (gw >= ni * nrhs)
        return;
    int const r = i0 + gw / nrhs;
    std::size_t const off = static_cast<std::size_t>(gw % nrhs) * ldv;

    df32 acc = df_make(0.f, 0.f);
    for (int j = lane; j < i0; j += 32)
        acc = df_add_acc(acc, df_mul(
            df_make(luh[static_cast<std::size_t>(r) * n + j],
                    lul[static_cast<std::size_t>(r) * n + j]),
            df_make(yh[off + j], yl[off + j])));
    for (int o = 16; o > 0; o >>= 1) {
        float const oh = __shfl_down_sync(0xffffffffu, acc.hi, o);
        float const ol = __shfl_down_sync(0xffffffffu, acc.lo, o);
        acc = df_add_acc(acc, df_make(oh, ol));
    }
    if (lane == 0) {
        df32 const v = df_sub_acc(df_make(bh[off + r], bl[off + r]), acc);
        rh[off + r] = v.hi;
        rl[off + r] = v.lo;
    }
}

