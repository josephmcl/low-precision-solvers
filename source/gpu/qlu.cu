/*  Diagonal apply, one BLOCK per right-hand side. The single-RHS kernel
    launches one block on a 132-SM device; this is the same body with the
    vectors offset, so k right-hand sides fill k blocks. */
__global__ void k_diag_apply_L_mrhs(
    int const    n,
    int const    i0,
    int const    ni,
    int const    ib,
    int const    ldv,
    float const *luh,
    float const *lul,
    float const *dh,
    float const *dl,
    float const *rh,
    float const *rl,
    float       *yh,
    float       *yl) {

    __shared__ float ys[256], yls[256], rrh[256], rrl[256];
    int const t = threadIdx.x;
    std::size_t const off = static_cast<std::size_t>(blockIdx.x) * ldv;

    for (int sb = 0; sb < ni; sb += ib) {
        int const sw = (ni - sb < ib)? (ni - sb) : ib;
        if (t < sw) {
            df32 rr = df_make(rh[off + i0 + sb + t], rl[off + i0 + sb + t]);
            for (int j = 0; j < sb; ++j)
                rr = df_sub_acc(rr, df_mul(
                    df_make(luh[static_cast<std::size_t>(i0 + sb + t) * n + (i0 + j)],
                            lul[static_cast<std::size_t>(i0 + sb + t) * n + (i0 + j)]),
                    df_make(ys[j], yls[j])));
            rrh[t] = rr.hi;
            rrl[t] = rr.lo;
        }
        __syncthreads();
        if (t < sw) {
            float const *mh = dh + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            float const *ml = dl + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            df32 acc = df_make(0.f, 0.f);
            for (int q = 0; q < sw; ++q)
                acc = df_add_acc(acc, df_mul(df_make(mh[t * ib + q], ml[t * ib + q]),
                                             df_make(rrh[q], rrl[q])));
            ys[sb + t]  = acc.hi;
            yls[sb + t] = acc.lo;
        }
        __syncthreads();
    }
    for (int m = t; m < ni; m += blockDim.x) {
        yh[off + i0 + m] = ys[m];
        yl[off + i0 + m] = yls[m];
    }
}

__global__ void k_diag_apply_U_mrhs(
    int const    n,
    int const    i0,
    int const    ni,
    int const    ib,
    int const    ldv,
    float const *luh,
    float const *lul,
    float const *dh,
    float const *dl,
    float const *rh,
    float const *rl,
    float       *yh,
    float       *yl) {

    __shared__ float ys[256], yls[256], rrh[256], rrl[256];
    int const t = threadIdx.x;
    std::size_t const off = static_cast<std::size_t>(blockIdx.x) * ldv;

    for (int sb = ((ni - 1) / ib) * ib; sb >= 0; sb -= ib) {
        int const sw = (sb + ib <= ni)? ib : (ni - sb);
        if (t < sw) {
            df32 rr = df_make(rh[off + i0 + sb + t], rl[off + i0 + sb + t]);
            for (int j = sb + sw; j < ni; ++j)
                rr = df_sub_acc(rr, df_mul(
                    df_make(luh[static_cast<std::size_t>(i0 + sb + t) * n + (i0 + j)],
                            lul[static_cast<std::size_t>(i0 + sb + t) * n + (i0 + j)]),
                    df_make(ys[j], yls[j])));
            rrh[t] = rr.hi;
            rrl[t] = rr.lo;
        }
        __syncthreads();
        if (t < sw) {
            float const *mh = dh + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            float const *ml = dl + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            df32 acc = df_make(0.f, 0.f);
            for (int q = 0; q < sw; ++q)
                acc = df_add_acc(acc, df_mul(df_make(mh[t * ib + q], ml[t * ib + q]),
                                             df_make(rrh[q], rrl[q])));
            ys[sb + t]  = acc.hi;
            yls[sb + t] = acc.lo;
        }
        __syncthreads();
    }
    for (int m = t; m < ni; m += blockDim.x) {
        yh[off + i0 + m] = ys[m];
        yl[off + i0 + m] = yls[m];
    }
}

/*  The triangular solves for ONE right-hand side.

    The batched kernels above take their parallelism from the right-hand
    sides: the diagonal kernel is launched with one block per column of B and
    the off-diagonal one with a warp per (row, column of B). With a single
    right-hand side that is one block for the first and 32 for the second on a
    device with 132 SMs, and the diagonal kernel reads the factor down a column
    -- one cache line per lane. nsys at n = 16384 put the two solves at 22 ms a
    refinement step, about forty times what reading the triangle once costs.

    These walk the same 256-row groups right-looking instead. Once a group is
    solved its contribution is removed from EVERY remaining row at once, a warp
    per row reading 256 contiguous factor entries, so the width of the update
    is the height of the matrix rather than the number of right-hand sides.
    Inside a group the S-rung inverses are applied as before and the in-group
    elimination reads each row contiguously.

    The residual is accumulated group by group in DF32 rather than summed and
    subtracted once, so the result is not bit-identical to the batched path;
    like the S-rung itself it is a reordering that refinement absorbs, and it
    is gated on the iteration count and the verdict. LPS_TRSV_MRHS=1 selects
    the batched kernels for a comparison. */
/*  Application precision of the single right-hand-side solves. The factor is
    accurate to about 2^-(7.8 k) of itself, so at k <= 3 (about 23 bits) its hi
    word already carries more than the factor holds: the solve can read hi only
    and accumulate in fp32, which halves the factor traffic and drops the
    two-word arithmetic. The residual and the update of x stay in DF32, so the
    limiting accuracy is unchanged; only the contraction of the iteration can
    move, and the probe measures the operator as applied. LPS_APPLY=df32|fp32
    overrides the depth rule. */
static bool g_apply_f32 = false;

template <bool F32>
__device__ __forceinline__ df32 trsv_mac(df32 acc, float ah, float al, float bh, float bl) {
    if constexpr (F32)
        return df_make(fmaf(ah, bh, acc.hi), 0.f);
    else
        return df_add_acc(acc, df_mul(df_make(ah, al), df_make(bh, bl)));
}

template <bool F32>
__device__ __forceinline__ df32 trsv_warp_sum(df32 acc) {
    for (int o = 16; o > 0; o >>= 1) {
        float const oh = __shfl_down_sync(0xffffffffu, acc.hi, o);
        if constexpr (F32) {
            acc.hi += oh;
        } else {
            float const ol = __shfl_down_sync(0xffffffffu, acc.lo, o);
            acc = df_add_acc(acc, df_make(oh, ol));
        }
    }
    return acc;
}

template <bool F32>
__global__ void k_trsv1_update(
    int const    n,
    int const    r0,
    int const    nr,
    int const    c0,
    int const    nc,
    float const *luh,
    float const *lul,
    float const *yh,
    float const *yl,
    float       *rh,
    float       *rl) {

    int const gw   = (blockIdx.x * blockDim.x + threadIdx.x) >> 5;
    int const lane = threadIdx.x & 31;
    if (gw >= nr)
        return;
    std::size_t const row = static_cast<std::size_t>(r0 + gw) * n;

    df32 acc = df_make(0.f, 0.f);
    for (int j = lane; j < nc; j += 32)
        acc = trsv_mac<F32>(acc, luh[row + c0 + j], F32? 0.f : lul[row + c0 + j],
                            yh[c0 + j], F32? 0.f : yl[c0 + j]);
    acc = trsv_warp_sum<F32>(acc);
    if (lane == 0) {
        df32 const v = df_sub_acc(df_make(rh[r0 + gw], rl[r0 + gw]), acc);
        rh[r0 + gw] = v.hi;
        rl[r0 + gw] = v.lo;
    }
}

template <bool F32>
__global__ void k_trsv1_group_L(
    int const    n,
    int const    i0,
    int const    ni,
    int const    ib,
    float const *luh,
    float const *lul,
    float const *dh,
    float const *dl,
    float const *rh,
    float const *rl,
    float       *yh,
    float       *yl) {

    __shared__ float rsh[256], rsl[256], ysh[256], ysl[256];
    int const t = threadIdx.x, lane = t & 31, w = t >> 5;
    int const nw = blockDim.x >> 5;

    for (int m = t; m < ni; m += blockDim.x) {
        rsh[m] = rh[i0 + m];
        rsl[m] = rl[i0 + m];
    }
    __syncthreads();

    for (int sb = 0; sb < ni; sb += ib) {
        int const sw = (ni - sb < ib)? (ni - sb) : ib;
        /*  The inverse block times the sub-block's residual, a warp per row:
            a thread per row walked the row one entry at a time, 64 dependent
            loads each on its own cache line, and that chain was the whole
            cost of this kernel (104 us against 10 us for the update of every
            remaining row of the matrix). */
        {
            float const *mh = dh + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            float const *ml = dl + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            for (int row = w; row < sw; row += nw) {
                df32 acc = df_make(0.f, 0.f);
                for (int q = lane; q < sw; q += 32)
                    acc = trsv_mac<F32>(acc, mh[row * ib + q], F32? 0.f : ml[row * ib + q],
                                        rsh[sb + q], F32? 0.f : rsl[sb + q]);
                acc = trsv_warp_sum<F32>(acc);
                if (lane == 0) {
                    ysh[sb + row] = acc.hi;
                    ysl[sb + row] = acc.lo;
                }
            }
        }
        __syncthreads();

        /*  Remove this sub-block from the rows of the group still to come,
            a warp per row so the factor is read along the row. */
        for (int row = sb + sw + w; row < ni; row += nw) {
            std::size_t const base =
                static_cast<std::size_t>(i0 + row) * n + (i0 + sb);
            df32 acc = df_make(0.f, 0.f);
            for (int j = lane; j < sw; j += 32)
                acc = trsv_mac<F32>(acc, luh[base + j], F32? 0.f : lul[base + j],
                                    ysh[sb + j], F32? 0.f : ysl[sb + j]);
            acc = trsv_warp_sum<F32>(acc);
            if (lane == 0) {
                df32 const v = df_sub_acc(df_make(rsh[row], rsl[row]), acc);
                rsh[row] = v.hi;
                rsl[row] = v.lo;
            }
        }
        __syncthreads();
    }
    for (int m = t; m < ni; m += blockDim.x) {
        yh[i0 + m] = ysh[m];
        yl[i0 + m] = ysl[m];
    }
}

template <bool F32>
__global__ void k_trsv1_group_U(
    int const    n,
    int const    i0,
    int const    ni,
    int const    ib,
    float const *luh,
    float const *lul,
    float const *dh,
    float const *dl,
    float const *rh,
    float const *rl,
    float       *yh,
    float       *yl) {

    __shared__ float rsh[256], rsl[256], ysh[256], ysl[256];
    int const t = threadIdx.x, lane = t & 31, w = t >> 5;
    int const nw = blockDim.x >> 5;

    for (int m = t; m < ni; m += blockDim.x) {
        rsh[m] = rh[i0 + m];
        rsl[m] = rl[i0 + m];
    }
    __syncthreads();

    for (int sb = ((ni - 1) / ib) * ib; sb >= 0; sb -= ib) {
        int const sw = (sb + ib <= ni)? ib : (ni - sb);
        /*  The inverse block times the sub-block's residual, a warp per row:
            a thread per row walked the row one entry at a time, 64 dependent
            loads each on its own cache line, and that chain was the whole
            cost of this kernel (104 us against 10 us for the update of every
            remaining row of the matrix). */
        {
            float const *mh = dh + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            float const *ml = dl + static_cast<std::size_t>((i0 + sb) / ib) * ib * ib;
            for (int row = w; row < sw; row += nw) {
                df32 acc = df_make(0.f, 0.f);
                for (int q = lane; q < sw; q += 32)
                    acc = trsv_mac<F32>(acc, mh[row * ib + q], F32? 0.f : ml[row * ib + q],
                                        rsh[sb + q], F32? 0.f : rsl[sb + q]);
                acc = trsv_warp_sum<F32>(acc);
                if (lane == 0) {
                    ysh[sb + row] = acc.hi;
                    ysl[sb + row] = acc.lo;
                }
            }
        }
        __syncthreads();

        for (int row = w; row < sb; row += nw) {
            std::size_t const base =
                static_cast<std::size_t>(i0 + row) * n + (i0 + sb);
            df32 acc = df_make(0.f, 0.f);
            for (int j = lane; j < sw; j += 32)
                acc = trsv_mac<F32>(acc, luh[base + j], F32? 0.f : lul[base + j],
                                    ysh[sb + j], F32? 0.f : ysl[sb + j]);
            acc = trsv_warp_sum<F32>(acc);
            if (lane == 0) {
                df32 const v = df_sub_acc(df_make(rsh[row], rsl[row]), acc);
                rsh[row] = v.hi;
                rsl[row] = v.lo;
            }
        }
        __syncthreads();
    }
    for (int m = t; m < ni; m += blockDim.x) {
        yh[i0 + m] = ysh[m];
        yl[i0 + m] = ysl[m];
    }
}

bool trsv_single_rhs() {
    static int const batched = (std::getenv("LPS_TRSV_MRHS") != nullptr)? 1 : 0;
    return batched == 0;
}

void trsv_L_one(
    int const n, int const blk, int const ib,
    float const *luh, float const *lul, float const *dlh, float const *dll,
    float const *bh, float const *bl, float *yh, float *yl,
    float *rh, float *rl) {

    CUDA_CHECK(cudaMemcpyAsync(rh, bh, n * sizeof(float),
                               cudaMemcpyDeviceToDevice, 0));
    CUDA_CHECK(cudaMemcpyAsync(rl, bl, n * sizeof(float),
                               cudaMemcpyDeviceToDevice, 0));
    for (int i0 = 0; i0 < n; i0 += blk) {
        int const ni = (i0 + blk <= n)? blk : (n - i0);
        if (g_apply_f32)
            k_trsv1_group_L<true><<<1, 1024>>>(n, i0, ni, ib, luh, lul, dlh, dll, rh, rl, yh, yl);
        else
            k_trsv1_group_L<false><<<1, 1024>>>(n, i0, ni, ib, luh, lul, dlh, dll, rh, rl, yh, yl);
        KERNEL_CHECK();
        int const nr = n - i0 - ni;
        if (nr > 0) {
            if (g_apply_f32)
                k_trsv1_update<true><<<(nr * 32 + 255) / 256, 256>>>(n, i0 + ni, nr, i0, ni, luh, lul, yh, yl, rh, rl);
            else
                k_trsv1_update<false><<<(nr * 32 + 255) / 256, 256>>>(n, i0 + ni, nr, i0, ni, luh, lul, yh, yl, rh, rl);
            KERNEL_CHECK();
        }
    }
}

void trsv_U_one(
    int const n, int const blk, int const ib,
    float const *luh, float const *lul, float const *duh, float const *dul,
    float const *bh, float const *bl, float *yh, float *yl,
    float *rh, float *rl) {

    CUDA_CHECK(cudaMemcpyAsync(rh, bh, n * sizeof(float),
                               cudaMemcpyDeviceToDevice, 0));
    CUDA_CHECK(cudaMemcpyAsync(rl, bl, n * sizeof(float),
                               cudaMemcpyDeviceToDevice, 0));
    for (int i0 = ((n - 1) / blk) * blk; i0 >= 0; i0 -= blk) {
        int const ni = (i0 + blk <= n)? blk : (n - i0);
        if (g_apply_f32)
            k_trsv1_group_U<true><<<1, 1024>>>(n, i0, ni, ib, luh, lul, duh, dul, rh, rl, yh, yl);
        else
            k_trsv1_group_U<false><<<1, 1024>>>(n, i0, ni, ib, luh, lul, duh, dul, rh, rl, yh, yl);
        KERNEL_CHECK();
        if (i0 > 0) {
            if (g_apply_f32)
                k_trsv1_update<true><<<(i0 * 32 + 255) / 256, 256>>>(n, 0, i0, i0, ni, luh, lul, yh, yl, rh, rl);
            else
                k_trsv1_update<false><<<(i0 * 32 + 255) / 256, 256>>>(n, 0, i0, i0, ni, luh, lul, yh, yl, rh, rl);
            KERNEL_CHECK();
        }
    }
}

/*  The blocked drivers, batched. Same block sequence as the vendored
    single-vector ones, so each column sees the identical order. */
void trsv_L_mrhs(
    int const n, int const blk, int const ib, int const nrhs, int const ldv,
    float const *luh, float const *lul, float const *dlh, float const *dll,
    float const *bh, float const *bl, float *yh, float *yl,
    float *rh, float *rl) {

    if (nrhs == 1 && trsv_single_rhs()) {
        trsv_L_one(n, blk, ib, luh, lul, dlh, dll, bh, bl, yh, yl, rh, rl);
        return;
    }
    for (int i0 = 0; i0 < n; i0 += blk) {
        int const ni = (i0 + blk <= n)? blk : (n - i0);
        int const w  = ni * nrhs * 32;
        k_trsv_off_L_mrhs<<<(w + 255) / 256, 256>>>(
            n, i0, ni, nrhs, ldv, luh, lul, yh, yl, bh, bl, rh, rl);
        KERNEL_CHECK();
        k_diag_apply_L_mrhs<<<nrhs, 256>>>(
            n, i0, ni, ib, ldv, luh, lul, dlh, dll, rh, rl, yh, yl);
        KERNEL_CHECK();
    }
}

void trsv_U_mrhs(
    int const n, int const blk, int const ib, int const nrhs, int const ldv,
    float const *luh, float const *lul, float const *duh, float const *dul,
    float const *bh, float const *bl, float *yh, float *yl,
    float *rh, float *rl) {

    if (nrhs == 1 && trsv_single_rhs()) {
        trsv_U_one(n, blk, ib, luh, lul, duh, dul, bh, bl, yh, yl, rh, rl);
        return;
    }
    for (int i0 = ((n - 1) / blk) * blk; i0 >= 0; i0 -= blk) {
        int const ni = (i0 + blk <= n)? blk : (n - i0);
        int const w  = ni * nrhs * 32;
        k_trsv_off_U_mrhs<<<(w + 255) / 256, 256>>>(
            n, i0, ni, nrhs, ldv, luh, lul, yh, yl, bh, bl, rh, rl);
        KERNEL_CHECK();
        k_diag_apply_U_mrhs<<<nrhs, 256>>>(
            n, i0, ni, ib, ldv, luh, lul, duh, dul, rh, rl, yh, yl);
        KERNEL_CHECK();
    }
}

/*  One application of the left preconditioner B0^-1 = U^-1 L^-1 P to k
    columns: exactly what the stationary path does per step, reused so
    the two solvers share a preconditioner rather than each having one. */
/*  fp32 application at depth <= 3, DF32 above; LPS_APPLY=fp32|df32 forces one. */
void set_apply_precision(state const *s) {
    static int forced = -2;
    if (forced == -2) {
        char const *e = std::getenv("LPS_APPLY");
        forced = (e == nullptr)? -1 : (std::string(e) == "fp32")? 1 : (std::string(e) == "df32")? 0 : -1;
    }
    g_apply_f32 = (forced >= 0)? (forced == 1) : (s->kfac <= 3);
}

void apply_precond(
    state *s, int const n, int const nrhs, int const ld,
    float *inh, float *inl,          /* consumed, gathered in place */
    float *outh, float *outl,
    float *t1h, float *t1l) {
    set_apply_precision(s);

    int const T = launch::BLOCK_SIZE;
    int const g = (n + T - 1) / T;
    for (int c = 0; c != nrhs; ++c)
        LAUNCH((gather_kernel<<<g, T>>>(
            n, s->d_perm, inh + static_cast<std::size_t>(c) * ld,
            inl + static_cast<std::size_t>(c) * ld,
            outh + static_cast<std::size_t>(c) * ld,
            outl + static_cast<std::size_t>(c) * ld)));

    if (s->srung_ib != 0) {
        trsv_L_mrhs(n, 256, s->srung_ib, nrhs, ld, s->d_hi, s->d_lo,
                    s->d_dlh, s->d_dll, outh, outl, t1h, t1l,
                    s->d_th, s->d_tl);
        trsv_U_mrhs(n, 256, s->srung_ib, nrhs, ld, s->d_hi, s->d_lo,
                    s->d_duh, s->d_dul, t1h, t1l, outh, outl,
                    s->d_th, s->d_tl);
    } else {
        for (int c = 0; c != nrhs; ++c) {
            std::size_t const o = static_cast<std::size_t>(c) * ld;
            trsv_L_blocked(n, 256, s->d_hi, s->d_lo, outh + o, outl + o,
                           t1h + o, t1l + o, s->d_th, s->d_tl);
            trsv_U_blocked(n, 256, s->d_hi, s->d_lo, t1h + o, t1l + o,
                           outh + o, outl + o, s->d_th, s->d_tl);
        }
    }
}

/*  Workspace for GMRES-IR(j) on k columns. */
bool ensure_gmres(state *s, int const j, std::size_t const k) {

    if (s->gm_j == j && s->gm_k == k)
        return true;

    std::size_t const nk = s->n * k;
    struct { float **p; std::size_t n; } const want[] = {
        {&s->gm_vh, static_cast<std::size_t>(j + 1) * nk},
        {&s->gm_vl, static_cast<std::size_t>(j + 1) * nk},
        {&s->gm_wh, nk}, {&s->gm_wl, nk},
        {&s->gm_th, nk}, {&s->gm_tl, nk},
        {&s->gm_uh, nk}, {&s->gm_ul, nk},
        {&s->gm_hh, k * static_cast<std::size_t>(j + 1) * j},
        {&s->gm_hl, k * static_cast<std::size_t>(j + 1) * j},
        {&s->gm_yh, k * static_cast<std::size_t>(j)},
        {&s->gm_yl, k * static_cast<std::size_t>(j)},
        {&s->gm_sh, k}, {&s->gm_sl, k},
        {&s->gm_bh, k}, {&s->gm_bl, k},
    };
    for (auto const &w : want) {
        void *p = s->acquire(w.n * sizeof(float));
        if (p == nullptr)
            return false;
        *w.p = static_cast<float *>(p);
    }
    void *p = s->acquire(k * sizeof(int));
    if (p == nullptr)
        return false;
    s->gm_keff = static_cast<int *>(p);

    s->gm_j = j;
    s->gm_k = k;
    return true;
}

/*  j Arnoldi steps on Op(v) = B0^-1 (A v), starting from the normalized
    B0^-1 r, then the least squares and the update. One outer step.

    Modified Gram-Schmidt with ONE REORTHOGONALIZATION PASS, which the
    reference keeps because I + M can be severely nonnormal; dropping it
    is not a simplification, it is a different algorithm. */
void gmres_inner(
    state *s, int const n, int const nrhs, int const ld, int const j,
    float *rh, float *rl,          /* the residual, consumed */
    float *xh, float *xl) {        /* updated in place */

    int const T = launch::BLOCK_SIZE;
    int const g = (n + T - 1) / T;
    dim3 const gv((n + T - 1) / T, nrhs);
    int const gc = (nrhs + 255) / 256;
    std::size_t const nk = static_cast<std::size_t>(n) * nrhs;

    CUDA_CHECK(cudaMemset(s->gm_hh, 0,
        static_cast<std::size_t>(nrhs) * (j + 1) * j * sizeof(float)));
    CUDA_CHECK(cudaMemset(s->gm_hl, 0,
        static_cast<std::size_t>(nrhs) * (j + 1) * j * sizeof(float)));
    std::vector<int> const kf(nrhs, j);
    CUDA_CHECK(cudaMemcpy(s->gm_keff, kf.data(), nrhs * sizeof(int),
                          cudaMemcpyHostToDevice));

    /*  V_0 = B0^-1 r / || B0^-1 r ||. */
    apply_precond(s, n, nrhs, ld, rh, rl, s->gm_vh, s->gm_vl,
                  s->gm_th, s->gm_tl);
    k_df_dot_mrhs<<<nrhs, 256>>>(n, ld, s->gm_vh, s->gm_vl,
                                 s->gm_vh, s->gm_vl, s->gm_sh, s->gm_sl);
    KERNEL_CHECK();
    k_df_sqrt_scalars<<<gc, 256>>>(nrhs, s->gm_sh, s->gm_sl,
                                   s->gm_bh, s->gm_bl);
    KERNEL_CHECK();
    k_df_normalize_mrhs<<<gv, T>>>(n, nrhs, ld, 0, s->gm_bh, s->gm_bl,
                                   s->gm_bh, s->gm_vh, s->gm_vl,
                                   s->gm_keff);
    KERNEL_CHECK();

    for (int i = 0; i != j; ++i) {

        float *vi_h = s->gm_vh + static_cast<std::size_t>(i) * nk;
        float *vi_l = s->gm_vl + static_cast<std::size_t>(i) * nk;

        /*  w = B0^-1 (A v_i). */
        k_df_matvec_mrhs<<<(n * nrhs * 32 + 255) / 256, 256>>>(
            n, nrhs, ld, s->d_ah, s->d_al, vi_h, vi_l,
            s->gm_th, s->gm_tl);
        KERNEL_CHECK();
        /*  The triangular solve's intermediate is an n x k vector, not
            a per-column scalar. Passing gm_y here -- which is k*j --
            overran it by a factor of n/j and produced a backward error
            of 1e-2 rather than a crash. */
        apply_precond(s, n, nrhs, ld, s->gm_th, s->gm_tl,
                      s->gm_wh, s->gm_wl, s->gm_uh, s->gm_ul);

        for (int pass = 0; pass != 2; ++pass)
            for (int l = 0; l <= i; ++l) {
                float *vl_h = s->gm_vh + static_cast<std::size_t>(l) * nk;
                float *vl_l = s->gm_vl + static_cast<std::size_t>(l) * nk;
                k_df_dot_mrhs<<<nrhs, 256>>>(n, ld, vl_h, vl_l,
                                             s->gm_wh, s->gm_wl,
                                             s->gm_sh, s->gm_sl);
                KERNEL_CHECK();
                k_h_accum<<<gc, 256>>>(nrhs, j, l, i, s->gm_sh, s->gm_sl,
                                       s->gm_hh, s->gm_hl);
                KERNEL_CHECK();
                k_df_axpy_mrhs<<<gv, T>>>(n, nrhs, ld, -1.f,
                                          s->gm_sh, s->gm_sl, vl_h, vl_l,
                                          s->gm_wh, s->gm_wl);
                KERNEL_CHECK();
            }

        k_df_dot_mrhs<<<nrhs, 256>>>(n, ld, s->gm_wh, s->gm_wl,
                                     s->gm_wh, s->gm_wl,
                                     s->gm_sh, s->gm_sl);
        KERNEL_CHECK();
        k_df_sqrt_scalars<<<gc, 256>>>(nrhs, s->gm_sh, s->gm_sl,
                                       s->gm_sh, s->gm_sl);
        KERNEL_CHECK();
        k_h_accum<<<gc, 256>>>(nrhs, j, i + 1, i, s->gm_sh, s->gm_sl,
                               s->gm_hh, s->gm_hl);
        KERNEL_CHECK();

        if (i + 1 == j)
            break;
        float *vn_h = s->gm_vh + static_cast<std::size_t>(i + 1) * nk;
        float *vn_l = s->gm_vl + static_cast<std::size_t>(i + 1) * nk;
        CUDA_CHECK(cudaMemcpy(vn_h, s->gm_wh, nk * sizeof(float),
                              cudaMemcpyDeviceToDevice));
        CUDA_CHECK(cudaMemcpy(vn_l, s->gm_wl, nk * sizeof(float),
                              cudaMemcpyDeviceToDevice));
        k_df_normalize_mrhs<<<gv, T>>>(n, nrhs, ld, i + 1,
                                       s->gm_sh, s->gm_sl, s->gm_bh,
                                       vn_h, vn_l, s->gm_keff);
        KERNEL_CHECK();
    }

    k_gmres_lsq<<<gc, 256>>>(j, nrhs, s->gm_hh, s->gm_hl,
                             s->gm_bh, s->gm_bl, s->gm_keff,
                             s->gm_yh, s->gm_yl);
    KERNEL_CHECK();

    /*  x += sum_i y_i V_i. */
    for (int i = 0; i != j; ++i) {
        float *vi_h = s->gm_vh + static_cast<std::size_t>(i) * nk;
        float *vi_l = s->gm_vl + static_cast<std::size_t>(i) * nk;
        k_df_axpy_strided<<<gv, T>>>(n, nrhs, ld, j, i,
                                     s->gm_yh, s->gm_yl, vi_h, vi_l,
                                     xh, xl);
        KERNEL_CHECK();
    }
    (void)g;
}

/*  Blocked right-looking LU with the Ozaki-II trailing update.

    The panel, the bulk row interchange and the U12 block solve are the
    vendored ones, called in the vendored order -- this is deliberately a
    copy of int8lu_factor's per-panel loop with one block replaced, so the
    two arms differ in the trailing update and in nothing else. Anything
    the sliced arm gets from its panel, this gets identically.

    What is NOT reproduced: the whole-factor CUDA graph, the async and
    persistent panels, the look-ahead and the FUSE backends. Those are
    built around the sliced update's schedule. The comparison this
    supports is against the per-panel sliced path.

    Returns false if a trailing update was rejected -- Ozaki-II has no
    meaning on a zero row of L21 or a zero column of U12, and a silent
    wrong answer there would be worse than a failed factorization. */
bool oii_factor(
    int const       n,
    int const       b,
    int const       kfac,
    float          *d_ah,
    float          *d_al,
    int            *d_piv,
    Int8LUScratch  &sc,
    oii::state     *os) {

#ifdef LPS_DUMP
    lps_lift_dump(n, -1, 0, kfac, kfac, d_ah, d_al, d_piv,
                  nullptr, nullptr, nullptr, nullptr);
#endif
    for (int p = 0; p < n; p += b) {

        int const bb = (p + b <= n)? b : (n - p);

        launch_panel_coop(n, p, bb, d_ah, d_al, d_piv + p, sc.gv, sc.gi);
        if (n - bb > 0)
            LAUNCH((k_laswp_bulk<<<(n - bb + 255) / 256, 256>>>(
                        n, p, bb, d_piv + p, d_ah, d_al)));

        /*  The last panel has no trailing update, but it still has a
            state worth recording: the injected hook in int8lu_factor
            fires at the END of the loop body and so catches it, and
            the two arms have to produce the same number of snapshots
            or the reader sees a shorter factorization than happened. */
        if (p + bb >= n) {
#ifdef LPS_DUMP
            lps_lift_dump(n, p, bb, kfac, kfac, d_ah, d_al, d_piv,
                          nullptr, nullptr, nullptr, nullptr);
#endif
            continue;
        }

        u12_blocked(n, p, bb, d_ah, d_al);

        int const mp = n - p - bb;
        int const np = mp;

        /*  L21 = carrier[p+bb : n, p : p+bb], U12 = carrier[p : p+bb,
            p+bb : n], both read in place at leading dimension n, and the
            product subtracted into the trailing block. No gather: that is
            what the strides are for. */
        std::size_t const l21 = static_cast<std::size_t>(p + bb) * n + p;
        std::size_t const u12 = static_cast<std::size_t>(p) * n + (p + bb);
        std::size_t const s22 = static_cast<std::size_t>(p + bb) * n
                              + (p + bb);

        if (!oii::gemm_df32(os, mp, np,
                            d_ah + l21, d_al + l21, n,
                            d_ah + u12, d_al + u12, n,
                            d_ah + s22, d_al + s22, n,
                            true)) {
            std::fprintf(stderr,
                         "[qlu/oii] trailing update rejected at panel "
                         "p=%d (mp=%d)\n", p, mp);
            return false;
        }
#ifdef LPS_DUMP
        /*  Same hook the injected one in int8lu_factor calls, so both
            arms produce the same dump format. Null slice pointers: the
            Ozaki-II update reads its operands out of the carrier and
            keeps no int8 slices, and the reader reconstructs L21 and
            U12 from the carrier anyway. */
        lps_lift_dump(n, p, bb, kfac, kfac, d_ah, d_al, d_piv,
                      nullptr, nullptr, nullptr, nullptr);
#endif
    }
    return true;
}

/*  The fused trailing update, chosen per factorization.

    It reproduces the unfused update bit for bit -- factor words and pivot
    sequence identical, and the realized rho of the iteration matrix identical
    on all 288 depth pairs of the 48-cell grid -- so there is nothing to trade
    off; the reason it is not simply always on is shape. `k_int8lu_fused` aborts
    the PROCESS unless every panel has mp % 16 == 0 and np % 64 == 0, and with a
    uniform panel width mp = np = n - (j+1) b, so that reduces to n % 64 == 0 and
    b % 64 == 0. A SuiteSparse matrix at n = 2339 exits(4) on the first panel.

    Within the safe shapes, FUSE=5 is the TMA path and wants b = 256 with n a
    multiple of 256, and FUSE=3 is the 64x64 tile, which falls through to the
    16x16 kernel on its own tail panels. The vendored code reads the choice from
    the environment, which is therefore the only channel; an explicit setting
    from the caller always wins, and is captured on the first call so that a
    later shape cannot overwrite it.

    This runs after create, so the scratch for the unfused path is still
    allocated; folding that into create is a separate change (it is the term
    that makes the scratch scale with the depth). */
/*  The panel, chosen the same way and for the same reason.

    nsys at n = 16384, b = 256, k = 4 on an H100 NVL puts `k_panel_coop` at 48 %
    of all GPU kernel time -- the largest single kernel, and about five times off
    a memory-bound roof, which points at the grid.sync per column rather than the
    arithmetic. FLAG=3 is the same cooperative panel with three barriers a column
    instead of five: the panel kernel falls from 318.6 ms to 236.2 ms and the
    whole factorization from 548.8 ms to 465.5 ms, a 1.18x that costs nothing,
    because the factor it produces is bit-identical -- permutation and both DF32
    words -- at b = 128 and b = 256.

    The faster panels are not free. BLOCKFAC (1.52x) and PANEL2 (1.47x) both
    change the factor, so they are verdict-gated rather than hash-gated and are
    not selected here; L1A is 0.38x and stays off. As with the fused update, an
    explicit setting from the caller wins and is captured on the first call. */
void select_panel_variant() {
    static bool captured     = false;
    static bool caller_drives = false;
    static std::string want;
    if (!captured) {
        /*  If the caller set any of the vendored panel switches, leave the whole
            thing alone: those are tested for PRESENCE, not value, so PANEL2=0
            would turn the two-level panel ON and there is no way for us to
            express "off" on the caller's behalf. */
        for (char const *v : {"PANEL2", "ASYNC", "BLOCKFAC", "FLAG", "L1A",
                              "PANELPERSIST", "CALU", "MIX"})
            if (std::getenv(v) != nullptr)
                caller_drives = true;
        char const *e = std::getenv("LPS_PANEL");
        want = (e != nullptr)? e : "auto";
        captured = true;
    }
    /*  The block row U12.

        Default: U12 = S12 + G S12 with G = J - I, J the computed b x b inverse
        of L11. S12 is already in the carrier at storage precision, so only
        G S12 is formed from integer slices. Its depth is the PRODUCER depth
        k_P = k_T + 2, two levels below the trailing update's k_T: that is the
        first depth at which the sliced row reproduces the chain's convergence
        on every pair tested (1080 depth pairs at n = 2048, 3072, 2000: no
        regression, no improvement, realized rho within 4 % in the median).
        At k_T + 1 three clustered cells at n = 3072 that converge with the
        chain diverge; at k_T the gate fails outright. At n = 16384, b = 256
        the factor is 272 ms against 314 for the chain at k_T = 4 and 207
        against 254 at k_T = 2. Panels whose shape the product cannot take
        (b not a multiple of 32, or a trailing width not a multiple of 16) use
        the chain.

        LPS_U12=chain     the blocked triangular solve.
        LPS_U12=inverse   the solve as products with inverted 32 x 32 diagonal
                          blocks in storage precision.
        LPS_U12=sliced, sliced+1   k_P = k_T, k_T + 1, for experiments. */
    {
        char const *u = std::getenv("LPS_U12");
        std::string const w = (u != nullptr)? u : "sliced+2";
        if (w == "inverse")
            setenv("LPS_U12INV", "1", 1);
        else if (w == "sliced")
            setenv("LPS_U12S", "0", 1);
        else if (w == "sliced+1")
            setenv("LPS_U12S", "1", 1);
        else if (w == "sliced+2")
            setenv("LPS_U12S", "2", 1);
    }
    if (caller_drives || want == "off")
        return;
    if (want == "coop3") {
        setenv("FLAG", "3", 1);
        return;
    }
    if (want == "async") {
        setenv("ASYNC", "1", 1);
        return;
    }
    /*  auto, and "2level" explicitly. The panel is barrier-bound -- 2.5 us a
        grid.sync against 6.9 us of work a column at n = 16384 -- and the
        two-level panel halves the columns each synchronisation has to wait
        for: 372 ms against 465 ms for the factorization. It keeps full-height
        partial pivoting (max |L| = 1, the same growth factor and residual as
        the default to four digits), but it is not bit-identical, so it was
        gated on verdicts: 348 depth pairs over 58 cells, SuiteSparse included,
        no regression and two cells that converge where they did not.
        LPS_PANEL=coop3 is the bit-identical panel for a run that has to
        reproduce an older factor. */
    setenv("PANEL2", "1", 1);

    /*  Each 64-column sub-block of that panel as one resident kernel with a
        single grid barrier a column, instead of two launches a column. Same
        operations in the same order, row swaps deferred to the end of the
        sub-block, so the factor is bit-identical to the two-launch chain (72
        of 72 cells over four families, odd sizes, b = 64/128/256). 328 ms
        against 306 at n = 16384. LPS_PANEL=2level keeps the chain. */
    if (want != "2level")
        setenv("PANEL1B", "1", 1);
}

void select_fused_update(std::size_t const n, int const b) {
    static bool captured = false;
    static std::string caller_set;
    if (!captured) {
        char const *e = std::getenv("FUSE");
        caller_set = (e != nullptr)? e : "";
        captured = true;
    }
    if (!caller_set.empty())
        return;

    bool const shape_ok = (n % 64 == 0) && (b % 64 == 0);
    if (!shape_ok) {
        unsetenv("FUSE");
        return;
    }
    /*  The 128-tile kernel is a different one on each architecture: wgmma on
        sm_90a, tcgen05 from sm_100a (compiled only with -DTC5). Each compiles
        to a stub that issues no product on a part that lacks the instruction,
        so the choice is made from the device and never from the shape alone.
        Without either, the warp-MMA kernels run everywhere. */
    if (b == 256 && n % 256 == 0) {
        if (int8lu_has_wgmma())
            setenv("FUSE", "5", 1);
        else if (int8lu_has_tcgen05())
            setenv("FUSE", "6", 1);
        else
            setenv("FUSE", "4", 1);
    } else if (b == 512 && n % 512 == 0 && int8lu_has_tcgen05() && INT8LU_TC5_KCHUNKS) {
        /*  tcgen05 runs b = 512 as two K chunks of 256; wgmma has no such path */
        setenv("FUSE", "6", 1);
    } else {
        setenv("FUSE", "3", 1);
    }
}

double factor(state *s) {

    if (s == nullptr)
        return 0.;

    /*  The pair set is decided in two places that must agree: the host
        list (npair/isarr/jsarr, built by int8lu_scratch_alloc at CREATE
        time from the host mirror) and the device loop (which reads
        lps_kfacL/lps_kfacU at FACTOR time). Calling set_depths after
        create leaves them describing different sets, and since the
        kernels index P by a shared pair counter that is a wrong answer
        rather than a crash. Cheap to check once per factorization. */
    {
        int dL = 0, dU = 0;
        CUDA_CHECK(cudaMemcpyFromSymbol(&dL, lps_kfacL, sizeof dL));
        CUDA_CHECK(cudaMemcpyFromSymbol(&dU, lps_kfacU, sizeof dU));
        int const wantL = (dL > 0)? dL : s->scratch.kfac;
        int const wantU = (dU > 0)? dU : s->scratch.kfac;
        if (wantL != s->scratch.kfacL || wantU != s->scratch.kfacU) {
            std::fprintf(stderr,
                "[qlu] depth mismatch: this state was built for "
                "(k_L=%d, k_U=%d) but the device is set to (%d, %d). "
                "set_depths must be called BEFORE create.\n",
                s->scratch.kfacL, s->scratch.kfacU, wantL, wantU);
            return -1.;
        }
    }

    timing::stopwatch watch;
    watch.start();

    if (s->which == kernel::oii) {
        if (!oii_factor(static_cast<int>(s->n), s->b, s->kfac,
                        s->d_hi, s->d_lo, s->d_piv, s->scratch,
                        s->oii_s))
            return -1.;
    } else {
        select_fused_update(s->n, s->b);
        int8lu_factor(s->blas, static_cast<int>(s->n), s->b, s->kfac,
                      UPD_INT8, s->d_hi, s->d_lo, s->d_piv, s->scratch);
    }

    /*  The inverses depend only on the factor, so they are built here and
        reused by every refinement step of every right-hand side. Timed
        with the factorization because that is where the work is: charging
        them to the solve would flatter it. */
    if (s->srung_ib != 0)
        srung_invert(static_cast<int>(s->n), s->srung_ib,
                     s->d_hi, s->d_lo,
                     s->d_dlh, s->d_dll, s->d_duh, s->d_dul);

    double const ms = watch.stop();
    s->times.factor += ms;
    double const t_perm0 = ms;

    /*  Compose the sequential interchanges into a permutation. Serial by
        nature and n ints against an O(n^3) factorization, so the host does
        it; a device scan would buy nothing. Outside the timed region only
        because getrf's own pivot list is what it consumes. */
    std::size_t const n = s->n;
    std::vector<int> piv(n), perm(n);
    CUDA_CHECK(cudaMemcpy(piv.data(), s->d_piv, n * sizeof(int),
                          cudaMemcpyDeviceToHost));
    for (std::size_t i = 0; i != n; ++i)
        perm[i] = static_cast<int>(i);
    for (std::size_t k = 0; k != n; ++k) {
        int const j = piv[k];
        if (j >= 0 && static_cast<std::size_t>(j) < n)
            std::swap(perm[k], perm[static_cast<std::size_t>(j)]);
    }
    CUDA_CHECK(cudaMemcpy(s->d_perm, perm.data(), n * sizeof(int),
                          cudaMemcpyHostToDevice));

    /*  The compose is host-serial between two blocking copies, so the
        stopwatch's device timeline measures it fairly. */
    s->times.perm += watch.stop() - t_perm0;

    return ms;
}

/*  Grow the solve workspace to hold `k` columns. The triangular solve's
    scratch (d_th/d_tl) stays one vector wide only in the single-column
    path; the batched kernels write per column, so it grows too. */
bool ensure_rhs(state *s, std::size_t const k) {

    if (k <= s->rhs_cap)
        return true;

    /*  Growing keeps the previous buffers in `owned` until destroy
        rather than freeing them. Bounded by the number of DISTINCT k a
        state is asked for, which is one in every current caller; it is
        retention, not a leak. */

    float **const work[] = {&s->d_bh, &s->d_bl, &s->d_xh, &s->d_xl,
                            &s->d_rh, &s->d_rl, &s->d_yh, &s->d_yl,
                            &s->d_zh, &s->d_zl, &s->d_th, &s->d_tl};
    std::size_t const bytes = s->n * k * sizeof(float);
    for (std::size_t i = 0; i != sizeof work / sizeof *work; ++i) {
        void *p = s->acquire(bytes);
        if (p == nullptr)
            return false;
        *work[i] = static_cast<float *>(p);
    }
    s->rhs_cap = k;
    return true;
}

double solve(
    state        *s,
    double       *d_x,
    double const *d_b,
    std::size_t const k,
    std::size_t  *n_iterations,
    int const     inner_j) {

    if (s == nullptr)
        return 0.;
    set_apply_precision(s);
    if (inner_j < 0 || inner_j > 8) {
        std::fprintf(stderr, "[qlu] inner_j=%d out of range; the "
                             "least squares is sized for j <= 8\n",
                     inner_j);
        return 0.;
    }

    int const   n = static_cast<int>(s->n);
    int const   T = launch::BLOCK_SIZE;
    int const   g = (n + T - 1) / T;
    std::size_t used = 0;

    CUDA_CHECK(cudaDeviceSynchronize());
    s->n_marks = 0;
    s->mark(-1);

    timing::stopwatch outer;
    outer.start();

    /*  Grow the solve workspace to k columns, n x k column major so a
        single-vector kernel still works on one column by pointer offset.
        Allocated here and not in create() because create() does not know
        k; it happens once per distinct k, not per solve. */
    if (!ensure_rhs(s, k))
        return 0.;
    if (inner_j > 0 && !ensure_gmres(s, inner_j, k))
        return 0.;
    /*  The hook may change the correction solver mid-solve. */
    int inner_j_cur = inner_j;
    s->last_refactor_requested = 0;

    std::size_t const nk = s->n * k;
    std::size_t const ld = s->n;

    LAUNCH((k_split_f64<<<(int)((nk + T - 1) / T), T>>>(
        (int)nk, d_b, s->d_bh, s->d_bl)));
    CUDA_CHECK(cudaMemset(s->d_xh, 0, nk * sizeof(float)));
    CUDA_CHECK(cudaMemset(s->d_xl, 0, nk * sizeof(float)));

    /*  The batched pass runs every column, converged ones included, so
        it reads the correction vector of columns that never had a
        gather -- a column that meets its test on the first residual is
        exactly that case, and its slot would otherwise hold whatever
        cudaMalloc returned. The values are discarded either way, but a
        NaN read is not free and reading uninitialized memory is not
        something to leave in on the grounds that the answer survives. */
    CUDA_CHECK(cudaMemset(s->d_yh, 0, nk * sizeof(float)));
    CUDA_CHECK(cudaMemset(s->d_yl, 0, nk * sizeof(float)));
    CUDA_CHECK(cudaMemset(s->d_zh, 0, nk * sizeof(float)));
    CUDA_CHECK(cudaMemset(s->d_zl, 0, nk * sizeof(float)));

    /*  ||b||_inf per column, for each column's relative stopping test. */
    std::vector<float> b_norm(k, 1.f);
    for (std::size_t c = 0; c != k; ++c) {
        CUDA_CHECK(cudaMemset(s->d_nrm, 0, sizeof(float)));
        LAUNCH((max_abs_kernel<<<g, T>>>(n, s->d_bh + c * ld, s->d_nrm)));
        float v = 0.f;
        CUDA_CHECK(cudaMemcpy(&v, s->d_nrm, sizeof(float),
                              cudaMemcpyDeviceToHost));
        b_norm[c] = (v > 0.f)? v : 1.f;
    }

    if (s->a_inf == 0.) {
        CUDA_CHECK(cudaMemset(s->d_nrm, 0, sizeof(float)));
        LAUNCH((k_inf_norm_rows<<<n, 256>>>(n, s->d_ah, s->d_al, s->d_nrm)));
        float av = 0.f;
        CUDA_CHECK(cudaMemcpy(&av, s->d_nrm, sizeof(float),
                              cudaMemcpyDeviceToHost));
        s->a_inf = (av > 0.f)? static_cast<double>(av) : 1.;
    }
    s->mark(3);

    /*  Per-column refinement state. Every column is carried through every
        pass of the batched solve, but a column that has met its own test
        stops taking the correction -- so its answer is what the column
        loop would have produced, bit for bit, and the batching costs it
        only wasted work. */
    /*  LPS_ITCAP overrides the iteration cap. Needed because the
        internal stopping metric cannot resolve the answer on
        ill-conditioned problems: the residual b - Ax is formed in DF32,
        so its floor is u_ff * ||A|| ||x||, and at kappa = 1e12 with
        ||x|| ~ 1e12 that is ~2e-3. The 1e-14 tolerance test is then
        unreachable and the solve always exits on the stall rule. Testing
        whether a divergent mode surfaces therefore has to be done by
        running a FIXED number of iterations and measuring the backward
        error outside, in double-double. */
    std::size_t cap = 60;
    if (char const *e = std::getenv("LPS_ITCAP"))
        cap = static_cast<std::size_t>(std::strtoul(e, nullptr, 10));

    /*  LPS_TRACE=1 prints the backward-error trajectory and suppresses
        BOTH early exits, so the full cap runs.

        Needed to tell two different claims apart when rho(M) >= 1 and
        the solve nevertheless reaches tolerance: either the divergent
        mode is pinned at rounding level and the trajectory stays flat,
        or the stopping rule fired before the mode surfaced and the
        trajectory turns back up. Those are not the same result, and the
        default stopping rule cannot distinguish them. */
    static int trace_env = -1;
    if (trace_env < 0) {
        char const *e = std::getenv("LPS_TRACE");
        /*  1: print and run every step (exits suppressed); 2: print only */
        trace_env = (e == nullptr)? 0 : (e[0] == '1')? 1 : (e[0] == '2')? 2 : 0;
    }
    int trace = (trace_env == 1)? 1 : 0;
    bool const tprint = trace_env != 0;
    static int stop_env = -1;
    if (stop_env < 0) {
        char const *e = std::getenv("LPS_STOP");
        stop_env = (e != nullptr && std::string(e) == "stall")? 0 : 1;
    }
    bool const stop_bound = stop_env == 1;

    /*  Per-call forced iteration count, for measuring STOPPING
        EFFICIENCY: the step at which ferr first reaches its floor,
        against the step the rule actually fires. Without that number a
        stopping-rule change is a replacement rather than a comparison --
        which is exactly how the A' metric shipped. A global env var
        cannot do this because the caller needs to sweep it per cell. */
    if (g_force_iters > 0) {
        cap = static_cast<std::size_t>(g_force_iters);
        trace = 1;                  /* suppress both early exits */
    }


    std::vector<double>      best(k, 1e30);
    std::vector<int>         stalled(k, 0);
    std::vector<char>        done(k, 0);
    std::vector<std::size_t> it_col(k, 0);
    /*  Successive correction norms. In exact arithmetic d_{k+1} = -M d_k,
        so this ratio IS the power-iteration estimate of rho(M) -- the
        divergence guard and the diagnostic are the same number. On the
        eig_clustered k=4 kappa=1e12 cell it reads ~1.10 from step 3,
        which is what the old rule missed entirely while the backward
        error improved. */
    std::vector<double>      d_prev(k, 0.);
    std::vector<double>      rho_est(k, 0.);
    std::vector<int>         growing(k, 0);
    std::vector<char>        diverged(k, 0);
    std::vector<int>         small(k, 0);
    std::vector<double>      best_rel(k, 1e30);
    std::vector<double>      rel_last(k, 1.);
    std::vector<char>        certified(k, 0);

    for (std::size_t it = 0; it != cap; ++it) {

        for (std::size_t c = 0; c != k; ++c) {
            if (done[c])
                continue;
            LAUNCH((k_df_residual_warp<<<(n * 32 + T - 1) / T, T>>>(
                n, s->d_ah, s->d_al, s->d_xh + c * ld, s->d_xl + c * ld,
                s->d_bh + c * ld, s->d_bl + c * ld,
                s->d_rh + c * ld, s->d_rl + c * ld)));
        }

        std::size_t n_active = 0;
        for (std::size_t c = 0; c != k; ++c) {
            if (done[c])
                continue;
            CUDA_CHECK(cudaMemset(s->d_nrm, 0, sizeof(float)));
            LAUNCH((max_abs_kernel<<<g, T>>>(n, s->d_rh + c * ld,
                                             s->d_nrm)));
            float r_norm = 0.f;
            CUDA_CHECK(cudaMemcpy(&r_norm, s->d_nrm, sizeof(float),
                                  cudaMemcpyDeviceToHost));
            /*  STOPPING IS ON THE CORRECTION NORM, not the residual.

                Both residual normalisations fail, in opposite
                directions. ||r||/||b|| floors at
                u_ff ||A|| ||x|| / ||b|| ~ 2e-3 when ||x|| ~ 1e12, so its
                tolerance never fires and it runs to the stall rule.
                ||r||/(||A|| ||x|| + ||b||) is a correct backward error
                and is EXCELLENT immediately -- 8.9e-16 by step 4 -- so
                it stops while the forward error is still 365x above its
                floor. Measured on clustered kappa=1e12 b=256: stopping
                at 4 steps gives ferr 1.98e-02, running to 12 gives
                7.4e-05 against a floor of 5.4e-05. A backward-error rule
                cannot drive forward accuracy when kappa is large,
                because a small backward error does not imply a small
                forward error -- that is the same fact that made bwd
                blind to divergence.

                ||d_k|| / ||x_k|| is the standard IR criterion and tracks
                the forward error directly, since d_k ~ e_k. It is also
                already computed here for the rho estimate, so the
                stopping rule, the divergence guard and the spectral
                diagnostic are one quantity. Lagged by one iteration
                because the correction is formed after this test. */
            /*  ||r|| / (||A|| ||x|| + ||b||), reported as the backward
                error, no longer the stopping test. The denominator's
                ||A|| ||x|| term is the magnitude the residual evaluation
                cancels against, so this floors at u_ff rather than at
                u_ff ||A|| ||x|| / ||b||. */
            CUDA_CHECK(cudaMemset(s->d_nrm, 0, sizeof(float)));
            LAUNCH((max_abs_kernel<<<g, T>>>(n, s->d_xh + c * ld,
                                             s->d_nrm)));
            float x_n = 0.f;
            CUDA_CHECK(cudaMemcpy(&x_n, s->d_nrm, sizeof(float),
                                  cudaMemcpyDeviceToHost));
            double const den = s->a_inf * static_cast<double>(x_n)
                             + static_cast<double>(b_norm[c]);
            double const rel = static_cast<double>(r_norm)
                             / (den > 0.? den : 1.);
            /*  The correction-norm test, on the previous iteration's
                correction. tol = 4 u_ff: below that the correction is
                at the carrier's own noise level and further steps move
                nothing. */
            double const drel = (d_prev[c] > 0. && x_n > 0.f)?
                                d_prev[c] / static_cast<double>(x_n) : 1.;
            if ((trace || tprint) && c == 0)
                std::printf("[trace] it %2zu  rel %.6e  drel %.3e  rho %.3e  small %d  stalled %d\n", it, rel, drel, rho_est[c], small[c], stalled[c]);

            /*  A small correction does not imply a small error.
                e_k = (I - E) d_k, since d_k = (I+M) e_k and
                (I+M)^-1 = I - E, so d_k ~ e_k only where E is small
                ALONG the error direction -- and ||E|| is 6e5 on
                eig_clustered. In the convergent regime the error aligns
                with directions where E is small, which is why the rule
                reproduced the 11-step run there; in marginal cells (rho
                near 1, s near 0) a small correction can sit beside a
                much larger error.

                Two guards: accept the stop only when the warmed-up
                correction ratio is below 1/2, or else require the
                small-correction condition on two consecutive steps. */
            bool const warm_ok = (rho_est[c] > 0. && rho_est[c] < 0.5);
            if (drel < 4. * 0x1p-49)
                ++small[c];
            else
                small[c] = 0;

            /*  SUCCESS IS THE RESIDUAL TEST. The correction test and the
                stall rule say when to stop iterating; neither certifies
                the answer. A column is converged only if, when one of them
                fires, the normalised residual

                    ||b - A x||_inf / (||A||_inf ||x||_inf + ||b||_inf)

                is at the level this residual can resolve. It is formed in
                DF32, so its own noise is a few u_ff (0.3 to 4 u_ff at the
                floor on the cells traced); RESID_TOL = 8 u_ff. A column
                that stops above it is reported as not converged
                (last_converged), whatever stopped it.

                Before this, three cells of the closed-loop set returned a
                backward error of 1e-9 to 1e-12 and a forward error up to
                1e4 as if solved: their residual wanders for the first four
                steps (2e-8, 8e-8, 6e-8, 7e-8, then a clean 0.3x a step),
                the correction ratio did not improve over those steps, and
                the stall rule ended the solve at step 4. */
            double const RESID_TOL = 8. * 0x1p-49;
            /*  A residual of exactly zero after the first step, or a
                non-finite norm, is an overflowed iterate, not a solution:
                the max-norm kernels drop NaNs. The entries themselves are
                checked where a column is certified. */
            bool const sane = std::isfinite(rel) && std::isfinite(static_cast<double>(x_n))
                           && !(it > 0 && (r_norm == 0.f || x_n == 0.f));
            bool resid_ok = sane && rel <= RESID_TOL;
            if (resid_ok && it > 0) {
                CUDA_CHECK(cudaMemset(s->d_nrm, 0, sizeof(float)));
                LAUNCH((any_nonfinite_kernel<<<g, T>>>(n, s->d_xh + c * ld, s->d_nrm)));
                LAUNCH((any_nonfinite_kernel<<<g, T>>>(n, s->d_rh + c * ld, s->d_nrm)));
                float bad = 0.f;
                CUDA_CHECK(cudaMemcpy(&bad, s->d_nrm, sizeof(float), cudaMemcpyDeviceToHost));
                if (bad != 0.f)
                    resid_ok = false;
            }
            rel_last[c] = sane? rel : 1e300;
            if (!sane && it > 3 && !trace) {
                /*  nothing can come back from an overflowed iterate */
                done[c] = 2; certified[c] = 0; diverged[c] = 1;
                continue;
            }

            /*  The a-posteriori bound of a contraction: with rho the ratio of
                the last two corrections, ||x - x_it|| <= rho/(1-rho) ||d_{it-1}||.
                Once that is below the carrier's resolution and the residual
                certifies, a further step changes nothing. The corrections
                themselves settle at about cond(A,x) u_ff -- 7 u_ff on the
                diagonally dominant timing matrix -- which is above the 4 u_ff
                test below, so without this a solve that reached its floor in
                two corrections ran two more and ended on the stall rule.
                LPS_STOP=stall keeps the earlier behaviour. */
            if (stop_bound && it > 2 && resid_ok && rho_est[c] > 0. && rho_est[c] < 0.5
                && rho_est[c] / (1. - rho_est[c]) * drel <= 4. * 0x1p-49 && !trace) {
                done[c] = 1;
                certified[c] = 1;
                continue;
            }
            if (it > 1 && small[c] >= 1 && (warm_ok || small[c] >= 2)) {
                if (!trace) {
                    /*  the correction is at the carrier's noise: nothing
                        further will move. Converged if the residual says
                        so, stagnated above tolerance otherwise. */
                    done[c] = resid_ok? 1 : 2;
                    certified[c] = resid_ok? 1 : 0;
                    continue;
                }
            }
            /*  Progress is progress in EITHER quantity. A stall is two
                steps in which neither the correction nor the residual
                improved; judged on the correction alone, a residual that
                was still falling 0.3x a step was cut off. */
            bool improved = false;
            if (drel < 0.7 * best[c]) { best[c] = drel; improved = true; }
            if (rel < 0.7 * best_rel[c]) { best_rel[c] = rel; improved = true; }
            if (improved) {
                stalled[c] = 0;
            } else if (++stalled[c] >= 2 && it > 3 && resid_ok) {
                if (!trace) {
                    /*  2, not 1: a stall is not convergence, and the
                        step hook below is the one place that can tell
                        the two apart. Everything else reads done[] as
                        a flag.

                        A stall ends the column only where the residual
                        is already at tolerance: the iteration has reached
                        its floor. Above tolerance two flat steps prove
                        nothing -- the residual of a contracting iteration
                        is not monotone at the start -- so the column goes
                        on to the cap and is reported from there. */
                    done[c] = 2;
                    certified[c] = 1;
                    continue;
                }
            }
            ++n_active;
        }
        s->mark(0);

        /*  A2 hook: after the stopping test, before the correction. It sees
            the per-column state and may (a) change inner_j_cur, in which
            case the GMRES workspace is made sure of here and any column
            that had only STALLED (done == 2) is put back to work under
            the new mode, or (b) return nonzero to end the solve with a
            refactor request. It is called on the exit path too: a stall
            or a divergence that ended every column is exactly what the
            policy has to see, and the loop used to leave before it was
            asked. Without a hook installed this block is a no-op. */
        if (g_step_hook != nullptr) {
            int want_j = inner_j_cur;
            int const rc = g_step_hook(g_step_hook_ctx, it, k, rho_est.data(),
                                       d_prev.data(), diverged.data(), done.data(),
                                       &want_j);
            if (rc != 0) { s->last_refactor_requested = 1; break; }
            if (want_j != inner_j_cur) {
                if (want_j > 0 && !ensure_gmres(s, want_j, k)) break;
                inner_j_cur = want_j;
                for (std::size_t c = 0; c != k; ++c)
                    if (done[c] == 2) {
                        done[c] = 0; stalled[c] = 0; best[c] = 1e30;
                        ++n_active;
                    }
            }
        }

        if (n_active == 0)
            break;

        /*  A converged column keeps its answer. The stationary path
            does that by skipping its update; the batched GMRES path
            runs every column at once, so the column is frozen instead
            by zeroing its residual -- B0^-1 0 is 0, beta is 0, the
            least squares sees an empty Krylov space, and the update it
            contributes is exactly zero. */
        if (inner_j_cur > 0) {
            for (std::size_t c = 0; c != k; ++c)
                if (done[c]) {
                    CUDA_CHECK(cudaMemset(s->d_rh + c * ld, 0,
                                          n * sizeof(float)));
                    CUDA_CHECK(cudaMemset(s->d_rl + c * ld, 0,
                                          n * sizeof(float)));
                }
            s->mark(1);
            gmres_inner(s, n, static_cast<int>(k), static_cast<int>(ld),
                        inner_j_cur, s->d_rh, s->d_rl, s->d_xh, s->d_xl);
            s->mark(2);
            for (std::size_t c = 0; c != k; ++c)
                if (!done[c])
                    ++it_col[c];
            s->mark(3);
            continue;
        }

        for (std::size_t c = 0; c != k; ++c) {
            if (done[c])
                continue;
            LAUNCH((gather_kernel<<<g, T>>>(n, s->d_perm,
                                            s->d_rh + c * ld,
                                            s->d_rl + c * ld,
                                            s->d_yh + c * ld,
                                            s->d_yl + c * ld)));
        }
        s->mark(1);

        /*  One batched pass over every column, converged ones included:
            compacting the active set would move columns in memory and
            buy nothing, since the pass is dominated by the shared walk
            over L\U rather than by the per-column arithmetic. */
        if (s->srung_ib != 0) {
            trsv_L_mrhs(n, 256, s->srung_ib, (int)k, (int)ld,
                        s->d_hi, s->d_lo, s->d_dlh, s->d_dll,
                        s->d_yh, s->d_yl, s->d_zh, s->d_zl,
                        s->d_th, s->d_tl);
            trsv_U_mrhs(n, 256, s->srung_ib, (int)k, (int)ld,
                        s->d_hi, s->d_lo, s->d_duh, s->d_dul,
                        s->d_zh, s->d_zl, s->d_yh, s->d_yl,
                        s->d_th, s->d_tl);
        } else {
            for (std::size_t c = 0; c != k; ++c) {
                if (done[c])
                    continue;
                trsv_L_blocked(n, 256, s->d_hi, s->d_lo,
                               s->d_yh + c * ld, s->d_yl + c * ld,
                               s->d_zh + c * ld, s->d_zl + c * ld,
                               s->d_th, s->d_tl);
                trsv_U_blocked(n, 256, s->d_hi, s->d_lo,
                               s->d_zh + c * ld, s->d_zl + c * ld,
                               s->d_yh + c * ld, s->d_yl + c * ld,
                               s->d_th, s->d_tl);
            }
        }
        s->mark(2);

        for (std::size_t c = 0; c != k; ++c) {
            if (done[c])
                continue;

            /*  rho estimate from the correction, BEFORE applying it. */
            CUDA_CHECK(cudaMemset(s->d_nrm, 0, sizeof(float)));
            LAUNCH((max_abs_kernel<<<g, T>>>(n, s->d_yh + c * ld,
                                             s->d_nrm)));
            float dn = 0.f;
            CUDA_CHECK(cudaMemcpy(&dn, s->d_nrm, sizeof(float),
                                  cudaMemcpyDeviceToHost));
            double const dcur = static_cast<double>(dn);
            if (d_prev[c] > 0. && dcur > 0.) {
                double const ratio = dcur / d_prev[c];
                rho_est[c] = ratio;
                /*  A margin and a minimum iteration count, for the
                    same reason the stall rule carries `it > 3`: the
                    first few corrections are not monotone, the residual
                    that produced them has its own noise, and a bare
                    "ratio > 1 twice" cut healthy solves off at step 2 --
                    clustered k=3 kappa=1e8 went from converging in 6 to
                    stopping at 3. The margin is 5 percent, which is
                    well inside the 1.10 the diverging cell shows. */
                /*  RECORD, do not stop.

                    Stopping on "two consecutive growing corrections"
                    was tried and costs accuracy: correction norms are
                    not monotone in the first few steps, and the rule
                    cut clustered k=3 kappa=1e8 from reaching 4.7e-18 in
                    6 iterations to stopping at 7.8e-15 in 3. The harm
                    from the old behaviour was never the wasted
                    iterations -- it was the FALSE VERDICT, and that is
                    fixed where verdicts are decided rather than by
                    truncating the solve. The margin is 5 percent, well
                    inside the 1.10 the diverging cell shows. */
                if (ratio > 1.05) {
                    if (++growing[c] >= 2 && it > 3)
                        diverged[c] = 1;
                } else {
                    growing[c] = 0;
                }
            }
            d_prev[c] = dcur;

            LAUNCH((add_correction_kernel<<<g, T>>>(
                n, s->d_yh + c * ld, s->d_yl + c * ld,
                s->d_xh + c * ld, s->d_xl + c * ld)));
            ++it_col[c];
        }
        s->mark(3);
    }

    for (std::size_t c = 0; c != k; ++c) {
        LAUNCH((combine_kernel<<<g, T>>>(n, s->d_xh + c * ld,
                                         s->d_xl + c * ld,
                                         d_x + c * s->n)));
        if (it_col[c] > used)
            used = it_col[c];
    }
    s->mark(3);

    double const ms = outer.stop();

    double *bucket[4] = {&s->times.residual, &s->times.gather,
                         &s->times.trsv,     &s->times.update};
    s->fold(bucket);

    if (n_iterations != nullptr)
        *n_iterations = used;

    /*  The worst column's rho estimate and whether any column was cut
        off for diverging. Exposed because a caller that only sees the
        backward error cannot tell a converged solve from a diverging
        one on an ill-conditioned problem. */
    s->last_rho = 0.;
    s->last_diverged = 0;
    s->last_converged = 1;
    s->last_rel = 0.;
    for (std::size_t c = 0; c != k; ++c) {
        s->last_rho = std::max(s->last_rho, rho_est[c]);
        if (diverged[c])
            s->last_diverged = 1;
        /*  A column that ran to the cap, or under a trace, never passed
            through an exit: it is judged on the last residual it formed,
            which is one correction behind. */
        bool const ok = done[c]? (certified[c] != 0)
                               : (rel_last[c] <= 8. * 0x1p-49);
        if (!ok)
            s->last_converged = 0;
        s->last_rel = std::max(s->last_rel, rel_last[c]);
    }

    return ms;
}

