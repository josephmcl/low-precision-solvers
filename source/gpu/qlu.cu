bool saturation(
    state      *s,
    int const   c0,
    int const   max_depth,
    int        *out,
    float      *g_max,
    int        *isat_i0,
    int const   qmax,
    int        *uf_out) {

    if (s == nullptr || out == nullptr)
        return false;

    int const n = static_cast<int>(s->n);
    int const width = (c0 + 256 <= n)? 256 : (n - c0);
    if (width <= 0)
        return false;

    int   *d_last = nullptr, *d_uf = nullptr, *d_si = nullptr;
    float *d_g = nullptr;
    if (!CUDA_CHECK(cudaMalloc(&d_last, n * sizeof(int))) ||
        !CUDA_CHECK(cudaMalloc(&d_uf, n * sizeof(int))) ||
        !CUDA_CHECK(cudaMalloc(&d_g, 2 * QLU_I0MAX * n * sizeof(float))) ||
        !CUDA_CHECK(cudaMalloc(&d_si, QLU_I0MAX * n * sizeof(int))))
        return false;

    k_saturation<<<n, 256>>>(n, c0, width, max_depth, qmax,
                             s->d_hi, s->d_lo, d_last, d_uf, d_g,
                             d_si, nullptr);
    KERNEL_CHECK();

    std::vector<int> uf(n);
    CUDA_CHECK(cudaMemcpy(out, d_last, n * sizeof(int),
                          cudaMemcpyDeviceToHost));
    CUDA_CHECK(cudaMemcpy(uf.data(), d_uf, n * sizeof(int),
                          cudaMemcpyDeviceToHost));
    if (g_max != nullptr)
        CUDA_CHECK(cudaMemcpy(g_max, d_g, 2 * QLU_I0MAX * n * sizeof(float),
                              cudaMemcpyDeviceToHost));
    if (isat_i0 != nullptr)
        CUDA_CHECK(cudaMemcpy(isat_i0, d_si, QLU_I0MAX * n * sizeof(int),
                              cudaMemcpyDeviceToHost));
    /*  Per-row underflow level, exposed because it is the only thing
        that separates two mechanisms for a cascade stopping: the
        residual reaching the fp32 floor (uf in range) versus
        contributions being absorbed while the residual is still
        representable (uf == 0). Inferring it from 19*log2(254) ~ 2^-149
        landing on the fp32 min denormal would be a coincidence
        argument, not a measurement. */
    if (uf_out != nullptr)
        std::copy(uf.begin(), uf.end(), uf_out);
    cudaFree(d_last);
    cudaFree(d_uf);
    cudaFree(d_g);
    cudaFree(d_si);

    /*  i_sat is one past the last level that changed anything. A row is
        valid unless its residual underflowed at or before that level --
        underflow afterwards just means an exhausted residual, which IS
        saturation. */
    bool clean = true;
    for (int i = 0; i != n; ++i) {
        if (uf[i] != 0 && uf[i] <= out[i])
            clean = false;
        out[i] += 1;
    }
    return clean;
}

void copy_factor(
    state *s,
    float *hi,
    float *lo,
    int   *perm) {

    if (s == nullptr)
        return;

    std::size_t const nn = s->n * s->n;
    CUDA_CHECK(cudaMemcpy(hi, s->d_hi, nn * sizeof(float),
                          cudaMemcpyDeviceToHost));
    CUDA_CHECK(cudaMemcpy(lo, s->d_lo, nn * sizeof(float),
                          cudaMemcpyDeviceToHost));
    CUDA_CHECK(cudaMemcpy(perm, s->d_perm, s->n * sizeof(int),
                          cudaMemcpyDeviceToHost));
}

